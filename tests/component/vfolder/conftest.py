@pytest.fixture()
async def vfolder_host_permission_fixture(
    db_engine: SAEngine,
    domain_fixture: DomainFixtureData,
    resource_policy_fixture: str,
) -> AsyncIterator[None]:
    """Update allowed_vfolder_hosts on the test domain and keypair resource policy.

    Grants all VFolderHostPermission flags for the "local" host so that
    vfolder operations (create, rename, delete, invite, etc.) are permitted.
    """
    all_perms: set[VFolderHostPermission] = set(VFolderHostPermission)
    host_perms = VFolderHostPermissionMap({"local": all_perms})
    async with db_engine.begin() as conn:
        await conn.execute(
            sa.update(domains)
            .where(domains.c.name == domain_fixture.domain_name)
            .values(allowed_vfolder_hosts=host_perms)
        )
        await conn.execute(
            sa.update(keypair_resource_policies)
            .where(keypair_resource_policies.c.name == resource_policy_fixture)
            .values(allowed_vfolder_hosts=host_perms)
        )
        # Also update the "default" keypair resource policy if it exists,
        # as new keypairs may reference it.
        await conn.execute(
            sa.update(keypair_resource_policies)
            .where(keypair_resource_policies.c.name == "default")
            .values(allowed_vfolder_hosts=host_perms)
        )
    yield
    # Restore empty permissions on teardown
    empty_perms = VFolderHostPermissionMap()
    async with db_engine.begin() as conn:
        await conn.execute(
            sa.update(domains)
            .where(domains.c.name == domain_fixture.domain_name)
            .values(allowed_vfolder_hosts=empty_perms)
        )
        await conn.execute(
            sa.update(keypair_resource_policies)
            .where(keypair_resource_policies.c.name == resource_policy_fixture)
            .values(allowed_vfolder_hosts=empty_perms)
        )


@pytest.fixture()
async def vfolder_factory(
    db_engine: SAEngine,
    domain_fixture: DomainFixtureData,
    admin_user_fixture: Any,
    vfolder_host_permission_fixture: None,
) -> AsyncIterator[VFolderFactory]:
    """Factory that inserts vfolder rows directly into DB (bypassing storage-proxy).

    This avoids the storage-proxy dependency for create operations.
    Yields a factory callable and cleans up all created vfolders on teardown.
    """
    created_ids: list[uuid.UUID] = []

    async def _create(**overrides: Any) -> VFolderFixtureData:
        unique = secrets.token_hex(4)
        vfolder_id = uuid.uuid4()
        user_uuid = uuid.UUID(str(overrides.get("user", admin_user_fixture.user_uuid)))
        async with db_engine.begin() as conn:
            personal_project_id = (
                await conn.execute(
                    sa.select(ProjectRow.__table__.c.id).where(
                        ProjectRow.__table__.c.creator_id == user_uuid,
                        ProjectRow.__table__.c.type == ProjectType.PERSONAL,
                    )
                )
            ).scalar_one()
        quota_scope_id = QuotaScopeID(
            scope_type=QuotaScopeType.USER,
            scope_id=user_uuid,
        )
        defaults: dict[str, Any] = {
            "id": vfolder_id,
            "name": f"test-vfolder-{unique}",
            "host": "local",
            "domain_name": domain_fixture.domain_name,
            "quota_scope_id": str(quota_scope_id),
            "usage_mode": VFolderUsageMode.GENERAL,
            "default_mount_permission": VFolderMountPolicy.READ_WRITE,
            "ownership_type": VFolderOwnershipType.USER,
            "user": str(user_uuid),
            # A folder lands in a project, which is what holds its name once.
            "group": str(personal_project_id),
            "creator": "admin-test@test.local",
            "status": VFolderOperationStatus.READY,
            "cloneable": False,
        }
        defaults.update(overrides)
        async with db_engine.begin() as conn:
            await conn.execute(sa.insert(vfolders).values(**defaults))
            # The node a create writes: the vfolder owns and governs itself.
            node_id = uuid.uuid4()
            await conn.execute(
                sa.insert(VirtualEntityRow.__table__).values(
                    id=node_id, entity_type=VFolderEntityType(), entity_id=defaults["id"]
                )
            )
            await conn.execute(
                sa.insert(EntityMembershipRow.__table__).values(
                    virtual_entity_id=node_id, member_entity_id=node_id, capped=False
                )
            )
            await conn.execute(
                sa.insert(ScopeBindingRow.__table__).values(
                    virtual_entity_id=node_id, scope_entity_id=node_id, permission_cap=None
                )
            )
            # A folder is created in its project, which owns and governs it; that is
            # what a project-scoped read walks.
            project_node = await conn.scalar(
                sa.select(VirtualEntityRow.__table__.c.id).where(
                    VirtualEntityRow.__table__.c.entity_type == ProjectEntityType(),
                    VirtualEntityRow.__table__.c.entity_id == uuid.UUID(defaults["group"]),
                )
            )
            if project_node is None:
                project_node = uuid.uuid4()
                await conn.execute(
                    sa.insert(VirtualEntityRow.__table__).values(
                        id=project_node,
                        entity_type=ProjectEntityType(),
                        entity_id=uuid.UUID(defaults["group"]),
                    )
                )
                await conn.execute(
                    sa.insert(EntityMembershipRow.__table__).values(
                        virtual_entity_id=project_node,
                        member_entity_id=project_node,
                        capped=False,
                    )
                )
                await conn.execute(
                    sa.insert(ScopeBindingRow.__table__).values(
                        virtual_entity_id=project_node,
                        scope_entity_id=project_node,
                        permission_cap=None,
                    )
                )
            await conn.execute(
                sa.insert(EntityMembershipRow.__table__).values(
                    virtual_entity_id=project_node, member_entity_id=node_id, capped=False
                )
            )
            await conn.execute(
                sa.insert(ScopeBindingRow.__table__).values(
                    virtual_entity_id=node_id, scope_entity_id=project_node, permission_cap=None
                )
            )
        created_ids.append(defaults["id"])
        return defaults

    yield _create

    # Cleanup: remove related rows first, then vfolders
    async with db_engine.begin() as conn:
        for vid in reversed(created_ids):
            await conn.execute(
                VirtualEntityRow.__table__.delete().where(
                    VirtualEntityRow.__table__.c.entity_type == VFolderEntityType(),
                    VirtualEntityRow.__table__.c.entity_id == vid,
                )
            )
            await conn.execute(vfolders.delete().where(vfolders.c.id == vid))


