@dataclass(frozen=True)
class TestSeedKeypairOf(TestSeedFieldCreator[UserData, KeyPairData]):
    """A keypair besides the one the user authorizes with.

    The policy name is a value an earlier row answered; this seed names none of its own.
    """

    resource_policy: str
    is_active: bool = True

    @override
    def kind(self) -> str:
        state = (
            Says("활성", english="active") if self.is_active else Says("비활성", english="inactive")
        )
        return Says(
            f"기본이 아닌 {state} 키페어 하나를 더 갖습니다",
            english=(
                f"has one more {in_language(state, Language.ENGLISH)} keypair "
                "besides the default one"
            ),
        )

    @override
    def owner_id(self, owner: UserData) -> UserID:
        return UserID(owner.id)

    @override
    def seed(self) -> KeypairCreator:
        token = secrets.token_hex(8).upper()
        return KeypairCreator(
            secrets=KeyPairSecrets(
                access_key=AccessKey(f"AK{token}"),
                secret_key=SecretValue(f"sk-{token}"),
            ),
            is_active=self.is_active,
            is_admin=False,
            resource_policy=self.resource_policy,
        )


@dataclass(frozen=True)
class TestSeedConfigFileOf[S](TestSeedRowFrom[S, AutoGeneratedFileData]):
    """An auto-generated file the row laid before it holds, left as not the default.

    ``owner_of`` names the owner from that row: a user, a project or a domain. The path is
    the row's name, so a scenario reads it at that path. Its content is a revision laid
    under it.
    """

    owner_of: Callable[[S], EntityIdentifier]
    path: str
    perm: str

    @override
    def kind(self) -> str:
        return Says("auto-generated file", english="Auto-generated file")

    @override
    def detail(self) -> str:
        return Says(f"권한 {self.perm}", english=f"permission {self.perm}")

    @override
    def name(self, naming: Naming) -> str:
        return self.path

    @override
    def seed(self, name: str, source: S) -> AutoGeneratedFileCreator:
        return AutoGeneratedFileCreator(
            owner=self.owner_of(source),
            entry=DotfileEntry(path=name, perm=self.perm, data=""),
        )


@dataclass(frozen=True)
class TestSeedConfigFileRevisionOf(
    TestSeedFieldCreator[AutoGeneratedFileData, AutoGeneratedFileRevisionData]
):
    """The next revision of the file's content. ``creator_id`` is a user an earlier row laid."""

    data: str
    creator_id: UserID

    @override
    def kind(self) -> str:
        return Says(
            f"내용이 {self.data!r} 인 revision 하나를 갖습니다",
            english=f"has one revision whose content is {self.data!r}",
        )

    @override
    def owner_id(self, owner: AutoGeneratedFileData) -> AutoGeneratedFileID:
        return owner.id

    @override
    def seed(self) -> AutoGeneratedFileRevisionCreator:
        return AutoGeneratedFileRevisionCreator(
            revision=AutoGeneratedFileRevisionSpec(data=self.data, creator_id=self.creator_id)
        )


@dataclass(frozen=True)
class TestSeedDefaultConfigFileOf(
    TestSeedBatchUpdate[AutoGeneratedFileData, AutoGeneratedFileData]
):
    """The file laid before it, set as the default of its path.

    The path holds no other file, so the clear that switching the default writes first
    changes nothing and only the mark is written.
    """

    path: str

    @override
    def kind(self) -> str:
        return Says("default auto-generated file", english="Default auto-generated file")

    @override
    def detail(self) -> str:
        return Says("그 경로의 default 로 지정됩니다", english="set as the default of its path")

    @override
    def name(self, naming: Naming) -> str:
        return self.path

    @override
    def updater(self, source: AutoGeneratedFileData) -> AutoGeneratedFileDefaultSetUpdater:
        return AutoGeneratedFileDefaultSetUpdater(auto_generated_file_id=source.id)


@dataclass(frozen=True)
class TestSeedLoginSessionOf(TestSeedFieldCreator[UserData, LoginSessionData]):
    """A login the user holds, made with the key an earlier row answered."""

    access_key: str
    status: LoginSessionStatus = LoginSessionStatus.ACTIVE

    @override
    def kind(self) -> str:
        return Says(
            f"상태가 {self.status.value} 인 로그인 세션 하나를 갖습니다",
            english=f"has one login session in status {self.status.value}",
        )

    @override
    def owner_id(self, owner: UserData) -> UserID:
        return UserID(owner.id)

    @override
    def seed(self) -> LoginSessionCreator:
        return LoginSessionCreator(
            session_token=secrets.token_hex(16), access_key=self.access_key, status=self.status
        )


@dataclass(frozen=True)
class TestSeedLoginHistoryOf(TestSeedFieldCreator[UserData, LoginHistoryData]):
    """The record one login attempt of the user left, under the user's own domain."""

    domain_name: str
    result: LoginAttemptResult = LoginAttemptResult.SUCCESS
    fail_reason: str | None = None
    client_ip: str | None = None

    @override
    def kind(self) -> str:
        return Says(
            f"로그인 시도 이력 하나를 갖습니다. 결과는 {self.result.value}",
            english=f"has one login attempt record whose result is {self.result.value}",
        )

    @override
    def owner_id(self, owner: UserData) -> UserID:
        return UserID(owner.id)

    @override
    def seed(self) -> LoginHistoryCreator:
        return LoginHistoryCreator(
            domain_name=self.domain_name,
            result=self.result,
            fail_reason=self.fail_reason,
            client_ip=self.client_ip,
        )
