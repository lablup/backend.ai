@dataclass(frozen=True)
class TheFileIsWritten(Then[AUserAndTheirOwnConfig, Answer]):
    """파일이 저장되고 빈 응답이 온다."""

    @override
    def says(self) -> str:
        return Says(
            "파일이 저장되고 빈 응답이 옵니다",
            english="the file is saved and an empty response comes back",
        )

    @override
    def look(self, laid: AUserAndTheirOwnConfig, answered: Answered[Answer]) -> list[Verdict]:
        response = answered.response
        if response is None:
            return [MissingResponse(answered.raised)]
        return [Same("response", type(response).__name__, "CreateDotfileResponse")]


@dataclass(frozen=True)
class NoDefaultFileIsListed(Then[AUserAndTheirOwnConfig, Answer]):
    """기본으로 표시된 파일이 없어 빈 목록이 온다."""

    @override
    def says(self) -> str:
        return Says(
            "기본으로 표시된 파일이 없어 빈 목록이 옵니다",
            english="no file is marked default, so an empty list comes back",
        )

    @override
    def look(self, laid: AUserAndTheirOwnConfig, answered: Answered[Answer]) -> list[Verdict]:
        listed = answered.response
        if listed is None:
            return [MissingResponse(answered.raised)]
        if not isinstance(listed, list):
            return [Same("response", type(listed).__name__, "list")]
        return [Same("files", [(one.path, one.permission, one.data) for one in listed], [])]


