@dataclass(frozen=True)
class AUserAndTheirOwnConfig:
    """설정 파일의 주인과, 그 주인에게 권한을 받은 사람. 둘은 같은 사람이다."""

    owner: UserData


@dataclass(frozen=True)
class SomeoneWithTheirOwnConfig(Given[Any, AUserAndTheirOwnConfig]):
    """도메인 하나와 사용자 하나. ``permissions``만큼 자기 사용자 권한을 받는다."""

    permissions: tuple[Permission, ...] = ()

    @override
    def describe(self) -> str:
        if self.permissions:
            names = ", ".join(str(p.name) for p in self.permissions)
            return Says(
                f"도메인 하나와 사용자 하나, 사용자는 자기 자신에게 {names} 권한을 받았습니다",
                english=(
                    f"one domain and one user, and the user holds the {names} permission on "
                    "themselves"
                ),
            )
        return Says(
            "도메인 하나와 사용자 하나, 사용자는 아무 권한도 받지 않았습니다",
            english="one domain and one user, and the user holds no permission",
        )

    @override
    async def lay(self, seeding: Any) -> AUserAndTheirOwnConfig:
        domain = await seeding.creating(TestSeedDomain(name_hint="home", description=WAS_HERE))
        owner = await seeding.within(SomeoneOf(domain))
        if self.permissions:
            await seeding.within(AGrant.on_user(owner, owner, *self.permissions))
        return AUserAndTheirOwnConfig(seeding.made(owner))


@dataclass(frozen=True)
class CreatingAConfigFile(When[AUserAndTheirOwnConfig, UserConfigAdapter, Answer]):
    """자기 설정 파일 하나를 만든다."""

    @override
    def operation(self) -> str:
        return "create_auto_generated_file"

    @override
    def describe(self, laid: AUserAndTheirOwnConfig) -> str:
        return Says(
            f"{laid.owner.username}이 자기 설정 파일을 하나 만듭니다",
            english=f"{laid.owner.username} writes one of their own config files",
        )

    @override
    async def call(self, adapter: UserConfigAdapter, laid: AUserAndTheirOwnConfig) -> Answer:
        with ActingAs(laid.owner):
            return await adapter.create_auto_generated_file(
                CreateAutoGeneratedFileInput(
                    user_id=UserID(laid.owner.id),
                    path=CONFIG_PATH,
                    perm=CONFIG_PERMISSION,
                    data=CONFIG_DATA,
                )
            )


