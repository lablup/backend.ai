@pytest.fixture
async def adapter(
    engine: ExtendedAsyncSAEngine,
    validators: V2ActionValidators,
    monitors: ActionMonitors,
) -> BootstrapScriptAdapter:
    provider = V2DBOpsProvider(engine)
    registry: ProcessorRegistry[Any] = ProcessorRegistry(
        ProcessorDependencies(
            monitors=monitors, validators=validators, repository=OpsRepository(provider)
        )
    )
    groups = registry.concern(ConcernMeta(Concern.ORGANIZATION))
    service = UserService(
        unwired(StorageSessionManager, "only purging a user with folders reaches it"),
        unwired(ValkeyStatClient, "no script operation reads user statistics"),
        unwired(AgentRegistry, "no script operation reaches the agents"),
        UserRepository(
            engine,
            provider,
            ShareOpsProvider(engine),
            ResourcePolicyOpsProvider(engine),
            KeyProviderPool(providers=[], write_provider_type=KeyProviderType.PLAIN),
        ),
        unwired(SchedulingController, "no script operation schedules sessions"),
        AutoGeneratedFileRepository(provider),
    )
    return BootstrapScriptAdapter(
        BootstrapScriptProcessors(
            groups.group(GroupMeta(UserEntityType())),
            groups.dangling_lookup_field_group(
                FieldGroupMeta(BootstrapScriptFieldType()),
                BootstrapScriptData,
                LookupBootstrapScriptOwnerAction,
                LookupBulkBootstrapScriptOwnerAction,
            ),
            groups.dangling_lookup_field_group(
                FieldGroupMeta(BootstrapScriptFieldType()),
                BootstrapScriptRevisionData,
                LookupBootstrapScriptOwnerAction,
                LookupBulkBootstrapScriptOwnerAction,
            ),
            service,
        )
    )
