from __future__ import annotations

import uuid
from unittest.mock import AsyncMock, MagicMock

import pytest

from ai.backend.common.data.entity.user import UserID
from ai.backend.manager.api.adapters.auto_generated_file.adapter import AutoGeneratedFileAdapter
from ai.backend.manager.dto.auto_generated_file_input import PurgeDefaultAutoGeneratedFileInput

STORED_PATH = "/etc/stored"

_USER = UserID(uuid.uuid4())


@pytest.fixture
def auto_generated_file_processors() -> MagicMock:
    processors = MagicMock()
    processors.search.run = AsyncMock(return_value=MagicMock(items=[MagicMock(path=STORED_PATH)]))
    processors.purge_default.run = AsyncMock()
    return processors


@pytest.fixture
def adapter(auto_generated_file_processors: MagicMock) -> AutoGeneratedFileAdapter:
    return AutoGeneratedFileAdapter(auto_generated_file_processors)


class TestStoredPathOutsideWorkDir:
    async def test_purge_allowed(
        self, adapter: AutoGeneratedFileAdapter, auto_generated_file_processors: MagicMock
    ) -> None:
        await adapter.purge_default_auto_generated_file(
            PurgeDefaultAutoGeneratedFileInput(owner=_USER, path=STORED_PATH)
        )
        auto_generated_file_processors.purge_default.run.assert_awaited_once()
