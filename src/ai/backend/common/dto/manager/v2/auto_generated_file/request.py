from __future__ import annotations

from uuid import UUID

from pydantic import Field, field_validator

from ai.backend.common.api_handlers import BaseRequestModel
from ai.backend.common.data.entity.auto_generated_file import AutoGeneratedFileID
from ai.backend.common.dotfile import validate_dotfile_path
from ai.backend.common.dto.manager.config.types import (
    MAXIMUM_DOTFILE_PATH_LENGTH,
    MAXIMUM_DOTFILE_SIZE,
    NO_NUL_PATTERN,
    AutoGeneratedFilePermission,
)
from ai.backend.common.dto.manager.query import (
    DateTimeFilter,
    EnumFilter,
    StringFilter,
    UUIDFilter,
)
from ai.backend.common.dto.manager.v2.auto_generated_file.types import (
    AutoGeneratedFileOrderField,
    AutoGeneratedFileScope,
    AutoGeneratedFileScopeType,
)
from ai.backend.common.dto.manager.v2.common import OrderDirection


class AutoGeneratedFileScopeInput(BaseRequestModel):
    """The one domain, project or user a file belongs to."""

    scope_type: AutoGeneratedFileScopeType = Field(description="Kind of the scope.")
    scope_id: UUID = Field(description="ID of the domain, project or user.")


class CreateAutoGeneratedFileInput(BaseRequestModel):
    """Add a file to a domain, project or user. The file is not the default of its path."""

    scope: AutoGeneratedFileScopeInput = Field(description="Scope the new file belongs to.")
    path: str = Field(
        max_length=MAXIMUM_DOTFILE_PATH_LENGTH,
        pattern=NO_NUL_PATTERN,
        description="Path the file is written to in a session.",
    )
    permission: AutoGeneratedFilePermission = Field(description="Unix file permission in octal.")
    data: str = Field(
        max_length=MAXIMUM_DOTFILE_SIZE,
        pattern=NO_NUL_PATTERN,
        description="Content of the first revision.",
    )

    @field_validator("path")
    @classmethod
    def _validate_path(cls, value: str) -> str:
        return validate_dotfile_path(value)


class PurgeAutoGeneratedFileInput(BaseRequestModel):
    """Remove a file that is not the default of its path."""

    id: AutoGeneratedFileID = Field(description="ID of the file.")


class SwitchDefaultAutoGeneratedFileInput(BaseRequestModel):
    """Make a file the default of its path in its scope."""

    scope: AutoGeneratedFileScopeInput = Field(description="Scope the file belongs to.")
    id: AutoGeneratedFileID = Field(description="ID of the file.")


class AutoGeneratedFileScopeTypeFilter(EnumFilter[AutoGeneratedFileScopeType]):
    """Filter for the kind of scope an auto-generated file belongs to."""


class AutoGeneratedFileFilter(BaseRequestModel):
    """Filter for auto-generated files."""

    entity_id: UUIDFilter | None = Field(
        default=None, description="Filter by auto-generated file ID."
    )
    scope_type: AutoGeneratedFileScopeTypeFilter | None = Field(
        default=None, description="Filter by the kind of scope the file belongs to."
    )
    scope_id: UUIDFilter | None = Field(
        default=None, description="Filter by the ID of the domain, project or user."
    )
    path: StringFilter | None = Field(default=None, description="Filter by path.")
    is_default: bool | None = Field(
        default=None, description="Filter by whether the file is the default of its path."
    )
    created_at: DateTimeFilter | None = Field(default=None, description="Filter by creation time.")
    updated_at: DateTimeFilter | None = Field(
        default=None, description="Filter by last update time."
    )

    AND: list[AutoGeneratedFileFilter] | None = Field(
        default=None, description="AND logical combinator."
    )
    OR: list[AutoGeneratedFileFilter] | None = Field(
        default=None, description="OR logical combinator."
    )
    NOT: list[AutoGeneratedFileFilter] | None = Field(
        default=None, description="NOT logical combinator."
    )


AutoGeneratedFileFilter.model_rebuild()


class AutoGeneratedFileOrder(BaseRequestModel):
    """Order specification for auto-generated files."""

    field: AutoGeneratedFileOrderField = Field(description="Field to order by.")
    direction: OrderDirection = Field(default=OrderDirection.ASC, description="Order direction.")


class ScopedSearchAutoGeneratedFilesInput(BaseRequestModel):
    """Input for searching auto-generated files within scopes."""

    scope: AutoGeneratedFileScope = Field(description="Scope (OR across all items).")
    filter: AutoGeneratedFileFilter | None = Field(default=None, description="Filter conditions.")
    order: list[AutoGeneratedFileOrder] | None = Field(
        default=None, description="Order specifications."
    )
    first: int | None = Field(default=None, description="Cursor pagination: number of items.")
    after: str | None = Field(default=None, description="Cursor pagination: after cursor.")
    last: int | None = Field(default=None, description="Cursor pagination: last N items.")
    before: str | None = Field(default=None, description="Cursor pagination: before cursor.")
    limit: int | None = Field(default=None, description="Offset pagination: maximum items.")
    offset: int | None = Field(default=None, description="Offset pagination: number to skip.")


class MySearchAutoGeneratedFilesInput(BaseRequestModel):
    """Input for searching the current user's own auto-generated files."""

    filter: AutoGeneratedFileFilter | None = Field(default=None, description="Filter conditions.")
    order: list[AutoGeneratedFileOrder] | None = Field(
        default=None, description="Order specifications."
    )
    first: int | None = Field(default=None, description="Cursor pagination: number of items.")
    after: str | None = Field(default=None, description="Cursor pagination: after cursor.")
    last: int | None = Field(default=None, description="Cursor pagination: last N items.")
    before: str | None = Field(default=None, description="Cursor pagination: before cursor.")
    limit: int | None = Field(default=None, description="Offset pagination: maximum items.")
    offset: int | None = Field(default=None, description="Offset pagination: number to skip.")
