from __future__ import annotations

from uuid import UUID

from pydantic import Field

from ai.backend.common.api_handlers import BaseResponseModel
from ai.backend.common.data.entity.auto_generated_file import AutoGeneratedFileID
from ai.backend.common.dto.manager.v2.auto_generated_file.types import AutoGeneratedFileScopeType


class AutoGeneratedFileNode(BaseResponseModel):
    id: AutoGeneratedFileID
    entity_id: AutoGeneratedFileID = Field(description="ID of the auto-generated file.")
    scope_type: AutoGeneratedFileScopeType
    scope_id: UUID
    path: str
    permission: str
    is_default: bool


class CreateAutoGeneratedFilePayload(BaseResponseModel):
    auto_generated_file: AutoGeneratedFileNode


class PurgeAutoGeneratedFilePayload(BaseResponseModel):
    entity_id: AutoGeneratedFileID = Field(description="ID of the purged file.")


class SearchAutoGeneratedFilesPayload(BaseResponseModel):
    """Payload for paginated auto-generated file search results."""

    items: list[AutoGeneratedFileNode] = Field(description="List of auto-generated file nodes.")
    total_count: int = Field(description="Total number of files matching the filter.")
    has_next_page: bool = Field(description="Whether there is a next page.")
    has_previous_page: bool = Field(description="Whether there is a previous page.")


class SwitchDefaultAutoGeneratedFilePayload(BaseResponseModel):
    auto_generated_file: AutoGeneratedFileNode
