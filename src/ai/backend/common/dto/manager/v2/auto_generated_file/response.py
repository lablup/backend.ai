from __future__ import annotations

from datetime import datetime
from uuid import UUID

from pydantic import Field

from ai.backend.common.api_handlers import BaseResponseModel
from ai.backend.common.data.entity.auto_generated_file import AutoGeneratedFileID
from ai.backend.common.data.entity.auto_generated_file_revision import AutoGeneratedFileRevisionID
from ai.backend.common.dto.manager.config.types import AutoGeneratedFilePermission
from ai.backend.common.dto.manager.v2.auto_generated_file.types import AutoGeneratedFileScopeType


class AutoGeneratedFileNode(BaseResponseModel):
    id: AutoGeneratedFileID
    entity_id: AutoGeneratedFileID = Field(description="ID of the auto-generated file.")
    scope_type: AutoGeneratedFileScopeType
    scope_id: UUID
    path: str
    is_default: bool
    created_at: datetime = Field(description="Creation timestamp.")
    updated_at: datetime = Field(description="Last update timestamp.")


class CreateAutoGeneratedFilePayload(BaseResponseModel):
    auto_generated_file: AutoGeneratedFileNode


class GetAutoGeneratedFilePayload(BaseResponseModel):
    auto_generated_file: AutoGeneratedFileNode


class PurgeAutoGeneratedFilePayload(BaseResponseModel):
    entity_id: AutoGeneratedFileID = Field(description="ID of the purged file.")


class SearchAutoGeneratedFilesPayload(BaseResponseModel):
    """Payload for paginated auto-generated file search results."""

    items: list[AutoGeneratedFileNode] = Field(description="List of auto-generated file nodes.")
    total_count: int = Field(description="Total number of files matching the filter.")
    has_next_page: bool = Field(description="Whether there is a next page.")
    has_previous_page: bool = Field(description="Whether there is a previous page.")


class SwitchDefaultAutoGeneratedFilePayload(BaseResponseModel):
    auto_generated_file: AutoGeneratedFileNode


class AutoGeneratedFileRevisionNode(BaseResponseModel):
    id: AutoGeneratedFileRevisionID = Field(description="ID of the revision.")
    field_id: AutoGeneratedFileRevisionID = Field(description="ID of the revision.")
    auto_generated_file_id: AutoGeneratedFileID = Field(description="ID of the file.")
    revision_number: int = Field(description="Number of the revision, counted from 1 per file.")
    data: str = Field(description="Content of the file at this revision.")
    permission: AutoGeneratedFilePermission = Field(
        description="Unix file permission in octal, at this revision."
    )
    creator_id: UUID | None = Field(
        description="ID of the user who wrote the revision. Null once that user is purged."
    )
    created_at: datetime = Field(description="Creation timestamp.")


class AddAutoGeneratedFileRevisionPayload(BaseResponseModel):
    revision: AutoGeneratedFileRevisionNode


class SearchAutoGeneratedFileRevisionsPayload(BaseResponseModel):
    """Payload for paginated auto-generated file revision search results."""

    items: list[AutoGeneratedFileRevisionNode] = Field(description="List of revisions.")
    total_count: int = Field(description="Total number of revisions matching the filter.")
    has_next_page: bool = Field(description="Whether there is a next page.")
    has_previous_page: bool = Field(description="Whether there is a previous page.")
