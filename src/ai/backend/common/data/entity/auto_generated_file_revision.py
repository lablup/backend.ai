from __future__ import annotations

from typing import override

from ai.backend.common.data.entity.auto_generated_file import AutoGeneratedFileEntityType
from ai.backend.common.data.entity.types import (
    EntityType,
    FieldIdentifier,
    FieldType,
)

__all__ = ("AutoGeneratedFileRevisionFieldType", "AutoGeneratedFileRevisionID")


class AutoGeneratedFileRevisionFieldType(FieldType):
    @override
    @classmethod
    def name(cls) -> str:
        return "auto_generated_file_revision"

    @override
    @classmethod
    def description(cls) -> str:
        return "One write of an auto-generated file's content, numbered within that file."

    @override
    @classmethod
    def owner_type(cls) -> type[EntityType]:
        return AutoGeneratedFileEntityType


class AutoGeneratedFileRevisionID(FieldIdentifier):
    @override
    @classmethod
    def field_type(cls) -> FieldType:
        return AutoGeneratedFileRevisionFieldType()
