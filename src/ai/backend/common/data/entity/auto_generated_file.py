from typing import override

from ai.backend.common.data.entity.types import DanglingFieldType, FieldIdentifier, FieldType


class AutoGeneratedFileFieldType(DanglingFieldType):
    @override
    @classmethod
    def name(cls) -> str:
        return "auto_generated_file"

    @override
    @classmethod
    def description(cls) -> str:
        return "A file an entity places in its sessions."


class AutoGeneratedFileID(FieldIdentifier):
    @override
    @classmethod
    def field_type(cls) -> FieldType:
        return AutoGeneratedFileFieldType()
