"""Write the CRD manifests into a Helm chart's templates directory, or check them for drift."""

from __future__ import annotations

import sys
from pathlib import Path

import click
import yaml

from ai.backend.kube.crd.schema import ALL_RESOURCES, build_crd

HEADER = "# Generated by `python -m ai.backend.kube.crd.generate`. Do not edit.\n"


def render_all() -> dict[str, str]:
    rendered: dict[str, str] = {}
    for resource in ALL_RESOURCES:
        crd = build_crd(resource)
        # Deleting a CRD deletes every CR of its kind, so `helm uninstall` must leave it.
        crd["metadata"]["annotations"] = {"helm.sh/resource-policy": "keep"}
        body = yaml.safe_dump(crd, sort_keys=False, default_flow_style=False)
        rendered[f"{crd['metadata']['name']}.yaml"] = HEADER + body
    return rendered


@click.command()
@click.argument("out_dir", type=click.Path(file_okay=False, path_type=Path))
@click.option("--check", is_flag=True, help="Fail if the files differ instead of writing them.")
def main(out_dir: Path, check: bool) -> None:
    rendered = render_all()
    stale = [name for name, body in rendered.items() if _read(out_dir / name) != body]
    if check:
        if stale:
            click.echo(f"stale CRD manifests: {', '.join(stale)}", err=True)
            sys.exit(1)
        return
    out_dir.mkdir(parents=True, exist_ok=True)
    for name in stale:
        (out_dir / name).write_text(rendered[name])
        click.echo(f"wrote {out_dir / name}")


def _read(path: Path) -> str | None:
    return path.read_text() if path.exists() else None


if __name__ == "__main__":
    main()
