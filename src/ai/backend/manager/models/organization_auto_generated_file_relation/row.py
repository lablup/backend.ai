from uuid import UUID

import sqlalchemy as sa
from sqlalchemy.orm import Mapped, mapped_column

from ai.backend.common.data.entity.auto_generated_file import AutoGeneratedFileID
from ai.backend.common.data.entity.types import EntityType
from ai.backend.manager.models.base import GUID, Base


class OrganizationAutoGeneratedFileRelationRow(Base):
    """A file an organization's sessions get at one path, and the permission it is written with.

    At most one file per organization and path. Removing the organization's graph node or the
    file deletes the row.
    """

    __tablename__ = "organization_auto_generated_file_relations"
    __table_args__ = (
        # The generated names run past PostgreSQL's 63-character limit.
        sa.ForeignKeyConstraint(
            ["organization_type", "organization_id"],
            ["virtual_entities.entity_type", "virtual_entities.entity_id"],
            name="fk_organization_auto_generated_file_relations_virtual_entities",
            ondelete="CASCADE",
        ),
        sa.UniqueConstraint(
            "organization_type",
            "organization_id",
            "path",
            name="uq_organization_auto_generated_file_relations_path",
        ),
        sa.CheckConstraint("char_length(perm) <= 4", name="perm_length"),
    )

    organization_type: Mapped[EntityType] = mapped_column(
        "organization_type", sa.String(32), primary_key=True
    )
    organization_id: Mapped[UUID] = mapped_column("organization_id", GUID(), primary_key=True)
    file_id: Mapped[AutoGeneratedFileID] = mapped_column(
        "file_id",
        GUID(AutoGeneratedFileID),
        sa.ForeignKey("dotfiles.id", ondelete="CASCADE"),
        primary_key=True,
        index=True,
    )
    path: Mapped[str] = mapped_column("path", sa.Text, nullable=False)
    perm: Mapped[str] = mapped_column("perm", sa.Text, nullable=False)
