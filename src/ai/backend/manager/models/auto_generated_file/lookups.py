from collections.abc import Sequence
from typing import Any, override
from uuid import UUID

import sqlalchemy as sa

from ai.backend.common.data.entity.auto_generated_file import AutoGeneratedFileID
from ai.backend.common.data.entity.types import EntityType, RuntimeEntityID
from ai.backend.manager.models.auto_generated_file.row import AutoGeneratedFileRow
from ai.backend.manager.models.specs.lookup import RuntimeFieldOwnerLookup


class AutoGeneratedFileOwnerLookup(RuntimeFieldOwnerLookup[AutoGeneratedFileID]):
    """The entity each named file belongs to, read from the type and id on the row."""

    @override
    def build_query(self, field_ids: Sequence[AutoGeneratedFileID]) -> sa.sql.Select[Any]:
        return sa.select(
            AutoGeneratedFileRow.id,
            AutoGeneratedFileRow.entity_id,
            AutoGeneratedFileRow.entity_type,
        ).where(AutoGeneratedFileRow.id.in_(field_ids))

    @override
    def owner_of(self, entity_type: EntityType, entity_id: UUID) -> RuntimeEntityID:
        return RuntimeEntityID(entity_type, entity_id)
