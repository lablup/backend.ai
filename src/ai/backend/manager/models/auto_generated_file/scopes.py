from collections.abc import Sequence
from dataclasses import dataclass
from typing import Any, override

import sqlalchemy as sa

from ai.backend.common.data.entity.types import EntityIdentifier
from ai.backend.manager.models.auto_generated_file.row import AutoGeneratedFileRow
from ai.backend.manager.models.clauses import QueryCondition
from ai.backend.manager.models.scopes import ExistenceCheck, ScopeTarget


@dataclass(frozen=True)
class AutoGeneratedFileTarget(ScopeTarget):
    """The files one domain, project or user owns."""

    owner: EntityIdentifier

    @override
    def scope_id(self) -> EntityIdentifier:
        return self.owner

    @override
    def to_condition(self) -> QueryCondition:
        owner = self.owner

        def inner() -> sa.sql.expression.ColumnElement[bool]:
            return sa.and_(
                AutoGeneratedFileRow.entity_type == owner.entity_type(),
                AutoGeneratedFileRow.entity_id == owner,
            )

        return inner

    @property
    @override
    def existence_checks(self) -> Sequence[ExistenceCheck[Any]]:
        # The action's scope gate already answered for the owner.
        return ()
