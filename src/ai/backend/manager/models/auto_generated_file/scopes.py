from __future__ import annotations

from abc import ABC
from collections.abc import Sequence
from dataclasses import dataclass
from typing import Any, override

import sqlalchemy as sa

from ai.backend.common.data.entity.domain import DomainEntityType, DomainID
from ai.backend.common.data.entity.project import ProjectEntityType, ProjectID
from ai.backend.common.data.entity.types import EntityIdentifier
from ai.backend.common.data.entity.user import UserEntityType, UserID
from ai.backend.common.exception import UnreachableError
from ai.backend.manager.models.auto_generated_file.row import AutoGeneratedFileRow
from ai.backend.manager.models.clauses import QueryCondition
from ai.backend.manager.models.scopes import ExistenceCheck, ScopeTarget

__all__ = (
    "AutoGeneratedFileTarget",
    "DomainAutoGeneratedFileTarget",
    "ProjectAutoGeneratedFileTarget",
    "UserAutoGeneratedFileTarget",
)


class AutoGeneratedFileTarget(ScopeTarget, ABC):
    """The files one domain, project or user owns."""

    @classmethod
    def of_owner(cls, owner: EntityIdentifier) -> AutoGeneratedFileTarget:
        match owner.entity_type():
            case entity_type if entity_type == DomainEntityType():
                return DomainAutoGeneratedFileTarget(DomainID(owner))
            case entity_type if entity_type == ProjectEntityType():
                return ProjectAutoGeneratedFileTarget(ProjectID(owner))
            case entity_type if entity_type == UserEntityType():
                return UserAutoGeneratedFileTarget(UserID(owner))
            case _:
                raise UnreachableError(
                    f"No auto-generated file is owned by a {owner.entity_type()}"
                )

    @override
    def to_condition(self) -> QueryCondition:
        owner = self.scope_id()

        def inner() -> sa.sql.expression.ColumnElement[bool]:
            return sa.and_(
                AutoGeneratedFileRow.entity_type == owner.entity_type(),
                AutoGeneratedFileRow.entity_id == owner,
            )

        return inner

    @property
    @override
    def existence_checks(self) -> Sequence[ExistenceCheck[Any]]:
        # The action's scope gate already answered for the owner.
        return ()


@dataclass(frozen=True)
class DomainAutoGeneratedFileTarget(AutoGeneratedFileTarget):
    """The files one domain owns."""

    domain_id: DomainID

    @override
    def scope_id(self) -> EntityIdentifier:
        return self.domain_id


@dataclass(frozen=True)
class ProjectAutoGeneratedFileTarget(AutoGeneratedFileTarget):
    """The files one project owns."""

    project_id: ProjectID

    @override
    def scope_id(self) -> EntityIdentifier:
        return self.project_id


@dataclass(frozen=True)
class UserAutoGeneratedFileTarget(AutoGeneratedFileTarget):
    """The files one user owns."""

    user_id: UserID

    @override
    def scope_id(self) -> EntityIdentifier:
        return self.user_id
