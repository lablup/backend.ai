from collections.abc import Sequence
from dataclasses import dataclass
from typing import override

from ai.backend.common.data.entity.auto_generated_file import AutoGeneratedFileID
from ai.backend.common.data.entity.types import EntityIdentifier
from ai.backend.common.data.entity.user import UserID
from ai.backend.manager.data.auto_generated_file.types import AutoGeneratedFileData
from ai.backend.manager.data.dotfile.types import DotfileEntry
from ai.backend.manager.errors.repository import ForeignKeyViolationError
from ai.backend.manager.errors.user import UserNotFound
from ai.backend.manager.models.auto_generated_file.row import AutoGeneratedFileRow
from ai.backend.manager.models.auto_generated_file.searchable_fields import (
    AutoGeneratedFileSearchableFields,
)
from ai.backend.manager.models.specs.creator import FieldCreator
from ai.backend.manager.models.specs.types import IntegrityErrorCheck


@dataclass(frozen=True)
class AutoGeneratedFileCreator(
    FieldCreator[EntityIdentifier, AutoGeneratedFileRow, AutoGeneratedFileData]
):
    owner: UserID
    entry: DotfileEntry

    @override
    def field_id(self, row: AutoGeneratedFileRow) -> AutoGeneratedFileID:
        return row.id

    @override
    def integrity_error_checks(self) -> Sequence[IntegrityErrorCheck]:
        return (IntegrityErrorCheck(violation_type=ForeignKeyViolationError, error=UserNotFound()),)

    @override
    def build_row(self, owner_id: EntityIdentifier) -> AutoGeneratedFileRow:
        return AutoGeneratedFileRow(
            entity_type=owner_id.entity_type(),
            entity_id=owner_id,
            path=self.entry.path,
            perm=self.entry.perm,
            data=self.entry.data,
        )

    @override
    def to_data(self, row: AutoGeneratedFileRow) -> AutoGeneratedFileData:
        return AutoGeneratedFileSearchableFields.own.to_data(row)
