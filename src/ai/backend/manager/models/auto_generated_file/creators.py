from collections.abc import Collection, Sequence
from dataclasses import dataclass
from typing import override

import sqlalchemy as sa

from ai.backend.common.data.entity.auto_generated_file import AutoGeneratedFileID
from ai.backend.common.data.entity.types import EntityIdentifier, EntityType, RuntimeEntityID
from ai.backend.manager.actions.types import ActionOperationType
from ai.backend.manager.data.auto_generated_file.types import AutoGeneratedFileData
from ai.backend.manager.data.dotfile.types import MAXIMUM_DOTFILE_COUNT, DotfileEntry
from ai.backend.manager.errors.base.entity import EntityNotFoundError
from ai.backend.manager.errors.repository import ForeignKeyViolationError
from ai.backend.manager.errors.storage import DotfileCreationFailed
from ai.backend.manager.models.auto_generated_file.row import AutoGeneratedFileRow
from ai.backend.manager.models.auto_generated_file.searchable_fields import (
    AutoGeneratedFileSearchableFields,
)
from ai.backend.manager.models.specs.creator import GuardedEntityCreator
from ai.backend.manager.models.specs.types import IntegrityErrorCheck, PreconditionCheck


@dataclass(frozen=True)
class AutoGeneratedFileCreator(GuardedEntityCreator[AutoGeneratedFileRow, AutoGeneratedFileData]):
    """Add one file to a domain, project or user; the row carries the owner, and the own and
    govern edges are derived from it."""

    owner: EntityIdentifier
    entry: DotfileEntry

    @override
    def precondition_checks(self) -> Sequence[PreconditionCheck]:
        # Variants count too, so creation cannot grow the owner's storage without bound.
        owned = (
            sa.select(sa.func.count())
            .select_from(AutoGeneratedFileRow)
            .where(
                AutoGeneratedFileRow.entity_type == self.owner.entity_type(),
                AutoGeneratedFileRow.entity_id == self.owner,
            )
            .scalar_subquery()
        )
        return (
            PreconditionCheck(
                finder=sa.select(sa.literal(True)).where(owned >= MAXIMUM_DOTFILE_COUNT),
                error=DotfileCreationFailed("Dotfile creation limit reached"),
            ),
        )

    @override
    def entity_id(self, row: AutoGeneratedFileRow) -> AutoGeneratedFileID:
        return row.id

    @override
    def created_in(self, row: AutoGeneratedFileRow) -> Collection[EntityIdentifier]:
        return (RuntimeEntityID(EntityType(row.entity_type), row.entity_id),)

    @override
    def integrity_error_checks(self) -> Sequence[IntegrityErrorCheck]:
        return (
            IntegrityErrorCheck(
                violation_type=ForeignKeyViolationError,
                error=EntityNotFoundError(
                    entity_type=self.owner.entity_type(), operation=ActionOperationType.CREATE
                ),
            ),
        )

    @override
    def build_row(self) -> AutoGeneratedFileRow:
        return AutoGeneratedFileRow(
            entity_type=self.owner.entity_type(),
            entity_id=self.owner,
            path=self.entry.path,
            perm=self.entry.perm,
            data=self.entry.data,
        )

    @override
    def to_data(self, row: AutoGeneratedFileRow) -> AutoGeneratedFileData:
        return AutoGeneratedFileSearchableFields.own.to_data(row)
