from uuid import UUID

import sqlalchemy as sa
from sqlalchemy.orm import Mapped, mapped_column

from ai.backend.common.data.entity.auto_generated_file import AutoGeneratedFileID
from ai.backend.common.data.entity.types import EntityType
from ai.backend.manager.models.base import GUID, Base
from ai.backend.manager.models.mixins.timestamp import LifecycleTimestampsMixin


class AutoGeneratedFileRow(LifecycleTimestampsMixin, Base):
    """One file; at most one variant per entity and path is the default. Its content is in
    ``auto_generated_file_revisions``."""

    __tablename__ = "auto_generated_files"
    __table_args__ = (
        # Removing the owner's graph node removes its files.
        sa.ForeignKeyConstraint(
            ["entity_type", "entity_id"],
            ["virtual_entities.entity_type", "virtual_entities.entity_id"],
            ondelete="CASCADE",
        ),
        sa.Index(
            "uq_auto_generated_files_is_default",
            "entity_type",
            "entity_id",
            "path",
            unique=True,
            postgresql_where=sa.text("is_default"),
        ),
    )

    id: Mapped[AutoGeneratedFileID] = mapped_column(
        GUID(AutoGeneratedFileID), primary_key=True, server_default=sa.text("uuid_generate_v7()")
    )
    entity_type: Mapped[EntityType] = mapped_column(sa.String(32), nullable=False)
    entity_id: Mapped[UUID] = mapped_column(GUID(), nullable=False)
    path: Mapped[str] = mapped_column(sa.Text, nullable=False)
    is_default: Mapped[bool] = mapped_column(sa.Boolean, nullable=False, server_default=sa.false())
