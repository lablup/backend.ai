from collections.abc import Sequence
from dataclasses import dataclass
from typing import Any, override

import sqlalchemy as sa
from sqlalchemy.orm import InstrumentedAttribute, aliased

from ai.backend.common.data.entity.auto_generated_file import AutoGeneratedFileID
from ai.backend.common.data.entity.user import UserID
from ai.backend.manager.data.auto_generated_file.types import AutoGeneratedFileData
from ai.backend.manager.models.auto_generated_file.row import AutoGeneratedFileRow
from ai.backend.manager.models.auto_generated_file.searchable_fields import (
    AutoGeneratedFileSearchableFields,
)
from ai.backend.manager.models.clauses import QueryCondition
from ai.backend.manager.models.specs.types import IntegrityErrorCheck
from ai.backend.manager.models.specs.updater import DataBatchUpdater, DataUpdater


@dataclass
class AutoGeneratedFileUpdater(DataUpdater[AutoGeneratedFileRow, AutoGeneratedFileData]):
    """Rewrite one auto-generated file, named by its own id."""

    auto_generated_file_id: AutoGeneratedFileID
    perm: str
    data: str

    @property
    @override
    def row_class(self) -> type[AutoGeneratedFileRow]:
        return AutoGeneratedFileRow

    @override
    def target_id_column(self) -> InstrumentedAttribute[Any]:
        return AutoGeneratedFileRow.id

    @override
    def target_id_value(self) -> AutoGeneratedFileID:
        return self.auto_generated_file_id

    @override
    def build_values(self) -> dict[str, Any]:
        return {"perm": self.perm, "data": self.data}

    @property
    @override
    def integrity_error_checks(self) -> Sequence[IntegrityErrorCheck]:
        return ()

    @override
    def to_data(self, row: AutoGeneratedFileRow) -> AutoGeneratedFileData:
        return AutoGeneratedFileSearchableFields.own.to_data(row)


@dataclass
class AutoGeneratedFileDefaultClearUpdater(
    DataBatchUpdater[AutoGeneratedFileRow, AutoGeneratedFileData]
):
    """Clear the default across the user's auto-generated files on the named one's path, the named one
    included. The rows are locked in id order first, so a concurrent switch waits."""

    user_id: UserID
    auto_generated_file_id: AutoGeneratedFileID

    @property
    @override
    def row_class(self) -> type[AutoGeneratedFileRow]:
        return AutoGeneratedFileRow

    @override
    def conditions(self) -> list[QueryCondition]:
        user_id, auto_generated_file_id = self.user_id, self.auto_generated_file_id

        def inner() -> sa.sql.expression.ColumnElement[bool]:
            target = aliased(AutoGeneratedFileRow)
            variant = aliased(AutoGeneratedFileRow)
            target_path = sa.select(target.path).where(
                target.entity_type == user_id.entity_type(),
                target.entity_id == user_id,
                target.id == auto_generated_file_id,
            )
            locked = (
                sa.select(variant.id)
                .where(
                    variant.entity_type == user_id.entity_type(),
                    variant.entity_id == user_id,
                    variant.path == target_path.scalar_subquery(),
                )
                .order_by(variant.id)
                .with_for_update()
            )
            return AutoGeneratedFileRow.id.in_(locked)

        return [inner]

    @override
    def build_values(self) -> dict[str, Any]:
        return {"is_default": False}

    @property
    @override
    def integrity_error_checks(self) -> Sequence[IntegrityErrorCheck]:
        return ()

    @override
    def to_data(self, row: AutoGeneratedFileRow) -> AutoGeneratedFileData:
        return AutoGeneratedFileSearchableFields.own.to_data(row)


@dataclass
class AutoGeneratedFileDefaultSetUpdater(
    DataBatchUpdater[AutoGeneratedFileRow, AutoGeneratedFileData]
):
    """Make the named auto-generated file the default of its path."""

    auto_generated_file_id: AutoGeneratedFileID

    @property
    @override
    def row_class(self) -> type[AutoGeneratedFileRow]:
        return AutoGeneratedFileRow

    @override
    def conditions(self) -> list[QueryCondition]:
        auto_generated_file_id = self.auto_generated_file_id
        return [lambda: AutoGeneratedFileRow.id == auto_generated_file_id]

    @override
    def build_values(self) -> dict[str, Any]:
        return {"is_default": True}

    @property
    @override
    def integrity_error_checks(self) -> Sequence[IntegrityErrorCheck]:
        return ()

    @override
    def to_data(self, row: AutoGeneratedFileRow) -> AutoGeneratedFileData:
        return AutoGeneratedFileSearchableFields.own.to_data(row)
