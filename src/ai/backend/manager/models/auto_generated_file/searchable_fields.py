"""What a file search can filter and order by, and how a file row becomes data."""

from __future__ import annotations

from typing import override

from ai.backend.common.data.entity.types import RuntimeEntityID
from ai.backend.manager.data.auto_generated_file.types import AutoGeneratedFileData
from ai.backend.manager.models.auto_generated_file.row import AutoGeneratedFileRow
from ai.backend.manager.models.specs.conditions.boolean import BoolConditions
from ai.backend.manager.models.specs.conditions.datetime import DateTimeConditions
from ai.backend.manager.models.specs.conditions.string import StringConditions
from ai.backend.manager.models.specs.conditions.uuid import UUIDConditions
from ai.backend.manager.models.specs.orders.column import ColumnOrder
from ai.backend.manager.models.specs.search.converter import RowDataConverter
from ai.backend.manager.models.specs.search.field import SearchableField


class _AutoGeneratedFileOwnFields(RowDataConverter[AutoGeneratedFileRow, AutoGeneratedFileData]):
    """The file's own columns; the file body cannot be filtered or ordered."""

    field_id = SearchableField(
        AutoGeneratedFileRow.id,
        UUIDConditions(AutoGeneratedFileRow.id),
        ColumnOrder(AutoGeneratedFileRow.id),
    )
    entity_type = SearchableField(
        AutoGeneratedFileRow.entity_type,
        StringConditions(AutoGeneratedFileRow.entity_type),
        ColumnOrder(AutoGeneratedFileRow.entity_type),
    )
    entity_id = SearchableField(
        AutoGeneratedFileRow.entity_id,
        UUIDConditions(AutoGeneratedFileRow.entity_id),
        ColumnOrder(AutoGeneratedFileRow.entity_id),
    )
    path = SearchableField(
        AutoGeneratedFileRow.path,
        StringConditions(AutoGeneratedFileRow.path),
        ColumnOrder(AutoGeneratedFileRow.path),
    )
    perm = SearchableField(AutoGeneratedFileRow.perm, None, None)
    data = SearchableField(AutoGeneratedFileRow.data, None, None)
    is_default = SearchableField(
        AutoGeneratedFileRow.is_default,
        BoolConditions(AutoGeneratedFileRow.is_default),
        ColumnOrder(AutoGeneratedFileRow.is_default),
    )
    created_at = SearchableField(
        AutoGeneratedFileRow.created_at,
        DateTimeConditions(AutoGeneratedFileRow.created_at),
        ColumnOrder(AutoGeneratedFileRow.created_at),
    )

    @override
    def to_data(self, row: AutoGeneratedFileRow) -> AutoGeneratedFileData:
        return AutoGeneratedFileData(
            id=self.field_id.read(row),
            entity=RuntimeEntityID(self.entity_type.read(row), self.entity_id.read(row)),
            path=self.path.read(row),
            perm=self.perm.read(row),
            data=self.data.read(row),
            is_default=self.is_default.read(row),
        )


class AutoGeneratedFileSearchableFields:
    own = _AutoGeneratedFileOwnFields()
