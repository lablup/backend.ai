"""Query specs for the auto_generated_file_revisions table."""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any, override

import sqlalchemy as sa
from sqlalchemy.orm import InstrumentedAttribute, aliased

from ai.backend.common.data.entity.auto_generated_file import AutoGeneratedFileID
from ai.backend.manager.data.auto_generated_file.types import AutoGeneratedFileRevisionData
from ai.backend.manager.models.auto_generated_file_revision.row import AutoGeneratedFileRevisionRow
from ai.backend.manager.models.auto_generated_file_revision.searchable_fields import (
    AutoGeneratedFileRevisionSearchableFields,
)
from ai.backend.manager.models.specs.querier import OwnedFieldQuerier


@dataclass
class CurrentAutoGeneratedFileRevisionQuerier(
    OwnedFieldQuerier[
        AutoGeneratedFileID, AutoGeneratedFileRevisionRow, AutoGeneratedFileRevisionData
    ]
):
    """The latest revision of each file, which is its current content."""

    @override
    def build_select(self) -> sa.sql.Select[Any]:
        later = aliased(AutoGeneratedFileRevisionRow)
        latest_number = (
            sa.select(sa.func.max(later.revision_number))
            .where(later.file_id == AutoGeneratedFileRevisionRow.file_id)
            .scalar_subquery()
        )
        return sa.select(AutoGeneratedFileRevisionRow).where(
            AutoGeneratedFileRevisionRow.revision_number == latest_number
        )

    @override
    def owner_id_column(self) -> InstrumentedAttribute[Any]:
        return AutoGeneratedFileRevisionRow.file_id

    @override
    def to_data(self, row: AutoGeneratedFileRevisionRow) -> AutoGeneratedFileRevisionData:
        return AutoGeneratedFileRevisionSearchableFields.own.to_data(row)
