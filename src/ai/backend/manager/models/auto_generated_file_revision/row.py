import sqlalchemy as sa
from sqlalchemy.orm import Mapped, mapped_column

from ai.backend.common.data.entity.auto_generated_file_revision import AutoGeneratedFileRevisionID
from ai.backend.common.data.entity.dotfile import DotfileID
from ai.backend.common.data.entity.user import UserID
from ai.backend.common.dto.manager.config.types import MAXIMUM_DOTFILE_SIZE
from ai.backend.manager.models.base import GUID, Base
from ai.backend.manager.models.mixins.timestamp import CreatedAtMixin


class AutoGeneratedFileRevisionRow(CreatedAtMixin, Base):
    """One write of a file's content; rows are only ever added."""

    __tablename__ = "auto_generated_file_revisions"
    __table_args__ = (
        sa.UniqueConstraint("file_id", "revision_number"),
        sa.CheckConstraint(f"char_length(data) <= {MAXIMUM_DOTFILE_SIZE}", name="data_length"),
    )

    id: Mapped[AutoGeneratedFileRevisionID] = mapped_column(
        "id",
        GUID(AutoGeneratedFileRevisionID),
        primary_key=True,
        server_default=sa.text("uuid_generate_v7()"),
    )
    file_id: Mapped[DotfileID] = mapped_column(
        "file_id",
        GUID(DotfileID),
        sa.ForeignKey("dotfiles.id", ondelete="CASCADE"),
        nullable=False,
    )
    revision_number: Mapped[int] = mapped_column("revision_number", sa.Integer, nullable=False)
    data: Mapped[str] = mapped_column("data", sa.Text, nullable=False)
    creator_id: Mapped[UserID | None] = mapped_column(
        "creator_id",
        GUID(UserID),
        sa.ForeignKey("users.uuid", ondelete="SET NULL"),
        nullable=True,
    )
