from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass
from typing import Any, override

import sqlalchemy as sa

from ai.backend.common.data.entity.auto_generated_file import AutoGeneratedFileID
from ai.backend.common.data.entity.types import EntityIdentifier
from ai.backend.manager.models.auto_generated_file_revision.row import AutoGeneratedFileRevisionRow
from ai.backend.manager.models.clauses import QueryCondition
from ai.backend.manager.models.scopes import ExistenceCheck, ScopeTarget


@dataclass(frozen=True)
class AutoGeneratedFileRevisionTarget(ScopeTarget):
    """The revisions of one file."""

    file_id: AutoGeneratedFileID

    @override
    def scope_id(self) -> EntityIdentifier:
        return self.file_id

    @override
    def to_condition(self) -> QueryCondition:
        file_id = self.file_id

        def inner() -> sa.sql.expression.ColumnElement[bool]:
            return AutoGeneratedFileRevisionRow.file_id == file_id

        return inner

    @property
    @override
    def existence_checks(self) -> Sequence[ExistenceCheck[Any]]:
        # The action's scope gate already answered for the file.
        return ()
