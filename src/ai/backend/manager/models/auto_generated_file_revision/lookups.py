"""Lookup specs for the auto_generated_file_revisions table."""

from __future__ import annotations

from collections.abc import Sequence
from typing import override
from uuid import UUID

import sqlalchemy as sa

from ai.backend.common.data.entity.auto_generated_file import AutoGeneratedFileID
from ai.backend.common.data.entity.auto_generated_file_revision import AutoGeneratedFileRevisionID
from ai.backend.manager.models.auto_generated_file_revision.row import AutoGeneratedFileRevisionRow
from ai.backend.manager.models.specs.lookup import FieldOwnerLookup


class AutoGeneratedFileRevisionOwnerLookup(
    FieldOwnerLookup[AutoGeneratedFileRevisionID, AutoGeneratedFileID]
):
    """The file a revision was written to."""

    @override
    def build_query(
        self, field_ids: Sequence[AutoGeneratedFileRevisionID]
    ) -> sa.sql.Select[tuple[AutoGeneratedFileRevisionID, AutoGeneratedFileID]]:
        return sa.select(
            AutoGeneratedFileRevisionRow.id, AutoGeneratedFileRevisionRow.file_id
        ).where(AutoGeneratedFileRevisionRow.id.in_(field_ids))

    @override
    def to_entity_id(self, value: UUID) -> AutoGeneratedFileID:
        return AutoGeneratedFileID(value)
