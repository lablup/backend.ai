from ai.backend.common.resilience.policies.retry import BackoffStrategy, RetryArgs, RetryPolicy
from ai.backend.common.resilience.resilience import Resilience
from ai.backend.manager.data.auto_generated_file.types import (
    AutoGeneratedFileData,
    AutoGeneratedFileRevisionSpec,
)
from ai.backend.manager.data.dotfile.types import DotfileEntries, DotfileEntry
from ai.backend.manager.errors.storage import DotfileNotFound
from ai.backend.manager.models.auto_generated_file.creators import AutoGeneratedFileCreator
from ai.backend.manager.models.auto_generated_file.scopes import AutoGeneratedFileTarget
from ai.backend.manager.models.auto_generated_file.searchable_fields import (
    AutoGeneratedFileSearchableFields,
)
from ai.backend.manager.models.auto_generated_file.searchers import AutoGeneratedFileSearcher
from ai.backend.manager.models.auto_generated_file.updaters import (
    AutoGeneratedFileDefaultClearUpdater,
    AutoGeneratedFileDefaultSetUpdater,
    AutoGeneratedFileUpdater,
)
from ai.backend.manager.models.auto_generated_file_revision.creators import (
    AutoGeneratedFileRevisionCreator,
)
from ai.backend.manager.models.auto_generated_file_revision.queriers import (
    CurrentAutoGeneratedFileRevisionQuerier,
)
from ai.backend.manager.models.specs.pagination import NoPagination
from ai.backend.manager.repositories.ops.v2.provider import V2DBOpsProvider
from ai.backend.manager.repositories.ops.v2.write import V2WriteOps

auto_generated_file_repository_resilience = Resilience(
    policies=[
        MetricPolicy(MetricArgs(domain=DomainType.REPOSITORY, layer=LayerType.DOTFILE_REPOSITORY)),
        RetryPolicy(
            RetryArgs(
                max_retries=10,
                retry_delay=0.1,
                backoff_strategy=BackoffStrategy.FIXED,
                non_retryable_exceptions=(BackendAIError,),
            )
        ),
    ]
)


class AutoGeneratedFileRepository:
    """Auto-generated files of an owner, each with its revisions and a default per path."""

    _ops: V2DBOpsProvider

    def __init__(self, ops_provider: V2DBOpsProvider) -> None:
        self._ops = ops_provider

    @auto_generated_file_repository_resilience.apply()
    async def default_files(self, owner: EntityIdentifier) -> DotfileEntries:
        """The owner's default files with the data of their latest revision."""
        async with self._ops.read_ops() as ops:
            result = await ops.search_with_scopes(
                [AutoGeneratedFileTarget.of_owner(owner)],
                AutoGeneratedFileSearcher(
                    pagination=NoPagination(),
                    conditions=[
                        AutoGeneratedFileSearchableFields.own.is_default.filter.equals(True)
                    ],
                    # Migrated rows share created_at; id keeps their original order.
                    orders=[
                        AutoGeneratedFileSearchableFields.own.created_at.order.apply(True),
                        AutoGeneratedFileSearchableFields.own.id.order.apply(True),
                    ],
                ),
            )
            revisions = await ops.query_owned_fields(
                CurrentAutoGeneratedFileRevisionQuerier(), [file.id for file in result.items]
            )
            return DotfileEntries(
                tuple(
                    DotfileEntry(file.path, file.perm, revisions[file.id].data)
                    for file in result.items
                )
            )

    @auto_generated_file_repository_resilience.apply()
    async def create(
        self, creator: AutoGeneratedFileCreator, creator_id: UserID
    ) -> AutoGeneratedFileData:
        """Add a file that is not the default of its path, with its data as revision 1."""
        async with self._ops.write_ops() as ops:
            created = await ops.create_entity(creator)
            await ops.create_field(
                created.id,
                AutoGeneratedFileRevisionCreator(
                    revision=AutoGeneratedFileRevisionSpec(
                        data=creator.entry.data, creator_id=creator_id
                    )
                ),
            )
            return created

    @auto_generated_file_repository_resilience.apply()
    async def update(
        self, updater: AutoGeneratedFileUpdater, revision: AutoGeneratedFileRevisionSpec
    ) -> AutoGeneratedFileData:
        """Rewrite a file's permission and append ``revision`` as its next revision."""
        async with self._ops.write_ops() as ops:
            updated = await ops.update_data(updater)
            if updated is None:
                raise DotfileNotFound
            await ops.create_field(
                updater.auto_generated_file_id,
                AutoGeneratedFileRevisionCreator(revision=revision),
            )
            return updated

    @auto_generated_file_repository_resilience.apply()
    async def switch_default(
        self, owner: EntityIdentifier, auto_generated_file_id: AutoGeneratedFileID
    ) -> AutoGeneratedFileData:
        """Make one of the owner's files the default of its path."""
        async with self._ops.write_ops() as ops:
            return await self._switch_default(ops, owner, auto_generated_file_id)

    async def _switch_default(
        self, ops: V2WriteOps, owner: EntityIdentifier, auto_generated_file_id: AutoGeneratedFileID
    ) -> AutoGeneratedFileData:
        scopes = [AutoGeneratedFileTarget.of_owner(owner)]
        # The clear locks the path's rows, so a concurrent switch waits for this one.
        await ops.batch_update_in_scopes(
            scopes,
            AutoGeneratedFileDefaultClearUpdater(
                owner=owner, auto_generated_file_id=auto_generated_file_id
            ),
        )
        switched = await ops.batch_update_in_scopes(
            scopes,
            AutoGeneratedFileDefaultSetUpdater(auto_generated_file_id=auto_generated_file_id),
        )
        if not switched:
            raise DotfileNotFound
        return switched[0]
