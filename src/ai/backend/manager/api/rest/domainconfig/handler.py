"""Domain config handler class using constructor dependency injection.

The dotfile API reads and writes the domain's default auto-generated files through
`AutoGeneratedFileAdapter`, gated by the auto-generated file permissions in the domain's scope.
"""

from __future__ import annotations

import logging
from http import HTTPStatus
from typing import Final

from ai.backend.common.api_handlers import APIResponse, BodyParam, QueryParam
from ai.backend.common.data.entity.domain import DomainName
from ai.backend.common.data.entity.user import UserID
from ai.backend.common.dto.manager.config.request import (
    CreateDomainDotfileRequest,
    DeleteDomainDotfileRequest,
    GetDomainDotfileRequest,
    UpdateDomainDotfileRequest,
)
from ai.backend.common.dto.manager.config.response import (
    CreateDotfileResponse,
    ListDotfilesResponse,
    UpdateDotfileResponse,
)
from ai.backend.logging.structured import StructuredLogger
from ai.backend.manager.api.adapters.auto_generated_file.adapter import AutoGeneratedFileAdapter
from ai.backend.manager.dto.auto_generated_file_input import (
    CreateAutoGeneratedFileInput,
    DeleteDefaultAutoGeneratedFileInput,
    UpdateDefaultAutoGeneratedFileInput,
)
from ai.backend.manager.dto.context import UserContext
from ai.backend.manager.services.domain.actions.lookup import LookupDomainAction
from ai.backend.manager.services.domain.processors import DomainProcessors

log: Final = StructuredLogger(logging.getLogger(__spec__.name))


class DomainConfigHandler:
    """Domain config (dotfile) API handler with constructor-injected dependencies."""

    def __init__(
        self, *, domain: DomainProcessors, auto_generated_file: AutoGeneratedFileAdapter
    ) -> None:
        self._domain = domain
        self._auto_generated_file = auto_generated_file

    async def create(
        self,
        body: BodyParam[CreateDomainDotfileRequest],
        ctx: UserContext,
    ) -> APIResponse:
        params = body.parsed
        target = await self._domain.lookup_name.run(
            LookupDomainAction(name=DomainName(params.domain))
        )
        await self._auto_generated_file.create_auto_generated_file(
            CreateAutoGeneratedFileInput(
                owner=target.entity_id(),
                creator_id=UserID(ctx.user_uuid),
                path=params.path,
                perm=params.permission,
                data=params.data,
            )
        )
        return APIResponse.build(HTTPStatus.OK, CreateDotfileResponse())

    async def list_or_get(
        self,
        query: QueryParam[GetDomainDotfileRequest],
        ctx: UserContext,
    ) -> APIResponse:
        params = query.parsed
        target = await self._domain.lookup_name.run(
            LookupDomainAction(name=DomainName(params.domain))
        )
        if params.path:
            result = await self._auto_generated_file.get_default_auto_generated_file_by_path(
                target.entity_id(), params.path
            )
            return APIResponse.build(HTTPStatus.OK, result)
        items = await self._auto_generated_file.list_default_auto_generated_files(
            target.entity_id()
        )
        return APIResponse.build(HTTPStatus.OK, ListDotfilesResponse(root=items))

    async def update(
        self,
        body: BodyParam[UpdateDomainDotfileRequest],
        ctx: UserContext,
    ) -> APIResponse:
        params = body.parsed
        target = await self._domain.lookup_name.run(
            LookupDomainAction(name=DomainName(params.domain))
        )
        await self._auto_generated_file.update_default_auto_generated_file(
            UpdateDefaultAutoGeneratedFileInput(
                owner=target.entity_id(),
                creator_id=UserID(ctx.user_uuid),
                path=params.path,
                perm=params.permission,
                data=params.data,
            )
        )
        return APIResponse.build(HTTPStatus.OK, UpdateDotfileResponse())

    async def delete(
        self,
        query: QueryParam[DeleteDomainDotfileRequest],
        ctx: UserContext,
    ) -> APIResponse:
        params = query.parsed
        target = await self._domain.lookup_name.run(
            LookupDomainAction(name=DomainName(params.domain))
        )
        result = await self._auto_generated_file.delete_default_auto_generated_file(
            DeleteDefaultAutoGeneratedFileInput(owner=target.entity_id(), path=params.path)
        )
        return APIResponse.build(HTTPStatus.OK, result)
