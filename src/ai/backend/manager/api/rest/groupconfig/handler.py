"""Group config handler class using constructor dependency injection.

The dotfile API reads and writes the project's default auto-generated files through
`AutoGeneratedFileAdapter`, gated by the auto-generated file permissions in the project's scope.
"""

from __future__ import annotations

import logging
from http import HTTPStatus
from typing import Final
from uuid import UUID

from ai.backend.common.api_handlers import APIResponse, BodyParam, QueryParam
from ai.backend.common.data.entity.domain import DomainName
from ai.backend.common.data.entity.project import ProjectID
from ai.backend.common.data.entity.user import UserID
from ai.backend.common.dto.manager.config.request import (
    CreateGroupDotfileRequest,
    DeleteGroupDotfileRequest,
    GetGroupDotfileRequest,
    UpdateGroupDotfileRequest,
)
from ai.backend.common.dto.manager.config.response import (
    CreateDotfileResponse,
    ListDotfilesResponse,
    UpdateDotfileResponse,
)
from ai.backend.logging.structured import StructuredLogger
from ai.backend.manager.api.adapters.auto_generated_file.adapter import AutoGeneratedFileAdapter
from ai.backend.manager.dto.auto_generated_file_input import (
    CreateDefaultAutoGeneratedFileInput,
    PurgeDefaultAutoGeneratedFileInput,
    UpdateDefaultAutoGeneratedFileInput,
)
from ai.backend.manager.dto.context import UserContext
from ai.backend.manager.services.project.actions.lookup import LookupProjectAction
from ai.backend.manager.services.project.processors import ProjectProcessors

log: Final = StructuredLogger(logging.getLogger(__spec__.name))


class GroupConfigHandler:
    """Group config (dotfile) API handler with constructor-injected dependencies."""

    def __init__(
        self, *, project: ProjectProcessors, auto_generated_file: AutoGeneratedFileAdapter
    ) -> None:
        self._project = project
        self._auto_generated_file = auto_generated_file

    async def _resolve(self, group: UUID | str, domain: str | None, ctx: UserContext) -> ProjectID:
        if isinstance(group, str):
            try:
                group = UUID(group)
            except ValueError:
                pass
        if isinstance(group, UUID):
            return ProjectID(group)
        result = await self._project.lookup.run(
            LookupProjectAction(
                domain_name=DomainName(domain or ctx.user_domain), project_name=group
            )
        )
        return result.entity_id()

    async def create(
        self,
        body: BodyParam[CreateGroupDotfileRequest],
        ctx: UserContext,
    ) -> APIResponse:
        params = body.parsed
        project_id = await self._resolve(params.group, params.domain, ctx)
        await self._auto_generated_file.create_default_auto_generated_file(
            CreateDefaultAutoGeneratedFileInput(
                owner=project_id,
                creator_id=UserID(ctx.user_uuid),
                path=params.path,
                perm=params.permission,
                data=params.data,
            )
        )
        return APIResponse.build(HTTPStatus.OK, CreateDotfileResponse())

    async def list_or_get(
        self,
        query: QueryParam[GetGroupDotfileRequest],
        ctx: UserContext,
    ) -> APIResponse:
        params = query.parsed
        project_id = await self._resolve(params.group, params.domain, ctx)
        if params.path:
            result = await self._auto_generated_file.get_default_auto_generated_file_by_path(
                project_id, params.path
            )
            return APIResponse.build(HTTPStatus.OK, result)
        items = await self._auto_generated_file.list_default_auto_generated_files(project_id)
        return APIResponse.build(HTTPStatus.OK, ListDotfilesResponse(root=items))

    async def update(
        self,
        body: BodyParam[UpdateGroupDotfileRequest],
        ctx: UserContext,
    ) -> APIResponse:
        params = body.parsed
        project_id = await self._resolve(params.group, params.domain, ctx)
        await self._auto_generated_file.update_default_auto_generated_file(
            UpdateDefaultAutoGeneratedFileInput(
                owner=project_id,
                creator_id=UserID(ctx.user_uuid),
                path=params.path,
                perm=params.permission,
                data=params.data,
            )
        )
        return APIResponse.build(HTTPStatus.OK, UpdateDotfileResponse())

    async def delete(
        self,
        query: QueryParam[DeleteGroupDotfileRequest],
        ctx: UserContext,
    ) -> APIResponse:
        params = query.parsed
        project_id = await self._resolve(params.group, params.domain, ctx)
        result = await self._auto_generated_file.purge_default_auto_generated_file(
            PurgeDefaultAutoGeneratedFileInput(owner=project_id, path=params.path)
        )
        return APIResponse.build(HTTPStatus.OK, result)
