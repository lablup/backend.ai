from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime

from ai.backend.common.data.entity.auto_generated_file_revision import AutoGeneratedFileRevisionID
from ai.backend.common.data.entity.dotfile import DotfileID
from ai.backend.common.data.entity.types import FieldData, RuntimeEntityID
from ai.backend.common.data.entity.user import UserID


@dataclass(frozen=True)
class AutoGeneratedFileRevisionData(FieldData):
    """One write of a file's content; the latest one is the current content."""

    id: AutoGeneratedFileRevisionID
    file_id: DotfileID
    revision_number: int
    data: str
    creator_id: UserID | None
    created_at: datetime


@dataclass(frozen=True)
class OrganizationAutoGeneratedFileRelationData(FieldData):
    """A file an organization's sessions get at one path, and the permission it is written with."""

    organization: RuntimeEntityID
    file_id: DotfileID
    path: str
    perm: str
