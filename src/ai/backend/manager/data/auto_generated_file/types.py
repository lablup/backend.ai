from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime
from typing import override

from ai.backend.common.data.entity.auto_generated_file import AutoGeneratedFileID
from ai.backend.common.data.entity.auto_generated_file_revision import AutoGeneratedFileRevisionID
from ai.backend.common.data.entity.types import EntityData, FieldData, RuntimeEntityID
from ai.backend.common.data.entity.user import UserID


@dataclass(frozen=True)
class AutoGeneratedFileData(EntityData):
    id: AutoGeneratedFileID
    entity: RuntimeEntityID
    path: str
    perm: str
    data: str
    is_default: bool

    @override
    def entity_id(self) -> AutoGeneratedFileID:
        return self.id


@dataclass(frozen=True)
class AutoGeneratedFileRevisionData(FieldData):
    """One write of a file's content; the latest one is the current content."""

    id: AutoGeneratedFileRevisionID
    file_id: AutoGeneratedFileID
    revision_number: int
    data: str
    creator_id: UserID | None
    created_at: datetime


@dataclass(frozen=True)
class OrganizationAutoGeneratedFileRelationData(FieldData):
    """A file an organization's sessions get at one path, and the permission it is written with."""

    organization: RuntimeEntityID
    file_id: AutoGeneratedFileID
    path: str
    perm: str
