from __future__ import annotations

from dataclasses import dataclass
from typing import override

from ai.backend.common.data.entity.types import EntityIdentifier
from ai.backend.manager.actions.types import ActionOperationType
from ai.backend.manager.actions.v2.single_entity.base import BaseSingleEntityAction
from ai.backend.manager.data.auto_generated_file.types import AutoGeneratedFileData
from ai.backend.manager.models.auto_generated_file.creators import AutoGeneratedFileCreator


@dataclass(frozen=True)
class CreateAutoGeneratedFileAction(BaseSingleEntityAction):
    """Add an auto-generated file under the user the creator names."""

    creator: AutoGeneratedFileCreator

    @override
    def entity_id(self) -> EntityIdentifier:
        return self.creator.owner

    @override
    @classmethod
    def operation_type(cls) -> ActionOperationType:
        return ActionOperationType.UPDATE

    @override
    @classmethod
    def action_name(cls) -> str:
        return "create_auto_generated_file"


@dataclass(frozen=True)
class CreateAutoGeneratedFileActionResult:
    data: AutoGeneratedFileData
