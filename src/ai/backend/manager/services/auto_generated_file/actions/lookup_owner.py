from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass
from typing import Any, override

from ai.backend.common.data.entity.auto_generated_file import AutoGeneratedFileID
from ai.backend.common.data.entity.types import EntityType, GlobalEntityType
from ai.backend.manager.actions.v2.field.bulk_lookup import LookupBulkRuntimeFieldOwnerOpsAction
from ai.backend.manager.actions.v2.field.lookup import LookupRuntimeFieldOwnerOpsAction
from ai.backend.manager.actions.v2.lookup.base import LookupKey
from ai.backend.manager.models.auto_generated_file.lookups import AutoGeneratedFileOwnerLookup


@dataclass(frozen=True)
class AutoGeneratedFileIDLookupKey(LookupKey):
    """An auto-generated file's id, resolved into the entity it belongs to."""

    auto_generated_file_id: AutoGeneratedFileID

    @override
    def kind(self) -> str:
        return "auto_generated_file_id"

    @override
    def to_dict(self) -> dict[str, Any]:
        return {"id": str(self.auto_generated_file_id)}


@dataclass
class LookupAutoGeneratedFileOwnerAction(LookupRuntimeFieldOwnerOpsAction[AutoGeneratedFileID]):
    """The entity one auto-generated file belongs to; its kind is a value on the row."""

    auto_generated_file_id: AutoGeneratedFileID

    @override
    @classmethod
    def entity_type(cls) -> EntityType:
        return GlobalEntityType()

    @override
    @classmethod
    def action_name(cls) -> str:
        return "lookup_auto_generated_file_owner"

    @override
    def lookup_key(self) -> LookupKey:
        return AutoGeneratedFileIDLookupKey(self.auto_generated_file_id)

    @override
    def field_id(self) -> AutoGeneratedFileID:
        return self.auto_generated_file_id

    @override
    def to_owner_lookup(self) -> AutoGeneratedFileOwnerLookup:
        return AutoGeneratedFileOwnerLookup()


@dataclass
class LookupBulkAutoGeneratedFileOwnerAction(
    LookupBulkRuntimeFieldOwnerOpsAction[AutoGeneratedFileID]
):
    """The entities several auto-generated files belong to."""

    auto_generated_file_ids: Sequence[AutoGeneratedFileID]

    @override
    @classmethod
    def entity_type(cls) -> EntityType:
        return GlobalEntityType()

    @override
    @classmethod
    def action_name(cls) -> str:
        return "lookup_bulk_auto_generated_file_owner"

    @override
    def to_lookup_key(self, field_id: AutoGeneratedFileID) -> LookupKey:
        return AutoGeneratedFileIDLookupKey(field_id)

    @override
    def field_ids(self) -> Sequence[AutoGeneratedFileID]:
        return tuple(self.auto_generated_file_ids)

    @override
    def to_owner_lookup(self) -> AutoGeneratedFileOwnerLookup:
        return AutoGeneratedFileOwnerLookup()
