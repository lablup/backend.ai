from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass
from typing import final, override

from ai.backend.common.data.entity.auto_generated_file import AutoGeneratedFileEntityType
from ai.backend.common.data.entity.types import EntityIdentifier, EntityType
from ai.backend.common.data.entity.user import UserID
from ai.backend.manager.actions.v2.ops.base import OperationScopeOpsAction
from ai.backend.manager.data.auto_generated_file.types import AutoGeneratedFileData
from ai.backend.manager.models.auto_generated_file.row import AutoGeneratedFileRow
from ai.backend.manager.models.auto_generated_file.scopes import AutoGeneratedFileTarget
from ai.backend.manager.models.auto_generated_file.searchers import AutoGeneratedFileSearcher
from ai.backend.manager.models.scopes import OperationScope


@dataclass(frozen=True)
class SearchAutoGeneratedFilesAction(
    OperationScopeOpsAction[AutoGeneratedFileRow, AutoGeneratedFileData]
):
    """Page through the files the named users own, OR'd across them."""

    user_ids: Sequence[UserID]
    searcher: AutoGeneratedFileSearcher

    @override
    @classmethod
    def entity_type(cls) -> EntityType:
        return AutoGeneratedFileEntityType()

    @final
    @override
    def scope_targets(self) -> Sequence[EntityIdentifier]:
        return tuple(self.user_ids)

    @final
    @override
    def operation_scopes(self) -> Sequence[OperationScope]:
        return tuple(AutoGeneratedFileTarget(user_id) for user_id in self.user_ids)

    @override
    def to_searcher(self) -> AutoGeneratedFileSearcher:
        return self.searcher

    @override
    @classmethod
    def action_name(cls) -> str:
        return "search_auto_generated_files"
