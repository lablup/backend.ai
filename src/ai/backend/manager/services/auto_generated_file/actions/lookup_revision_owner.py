from __future__ import annotations

from dataclasses import dataclass
from typing import override

from ai.backend.common.data.entity.auto_generated_file import (
    AutoGeneratedFileEntityType,
    AutoGeneratedFileID,
)
from ai.backend.common.data.entity.auto_generated_file_revision import AutoGeneratedFileRevisionID
from ai.backend.common.data.entity.types import EntityType
from ai.backend.manager.actions.v2.field.lookup import LookupFieldOwnerOpsAction
from ai.backend.manager.actions.v2.lookup.base import LookupKey
from ai.backend.manager.models.auto_generated_file_revision.lookups import (
    AutoGeneratedFileRevisionOwnerLookup,
)
from ai.backend.manager.services.auto_generated_file.actions.lookup_bulk_revision_owner import (
    AutoGeneratedFileRevisionIDLookupKey,
)


@dataclass(frozen=True)
class LookupAutoGeneratedFileRevisionOwnerAction(
    LookupFieldOwnerOpsAction[AutoGeneratedFileRevisionID, AutoGeneratedFileID]
):
    """The file a revision was written to."""

    auto_generated_file_revision_id: AutoGeneratedFileRevisionID

    @override
    @classmethod
    def entity_type(cls) -> EntityType:
        return AutoGeneratedFileEntityType()

    @override
    @classmethod
    def action_name(cls) -> str:
        return "lookup_auto_generated_file_revision_field_owner"

    @override
    def lookup_key(self) -> LookupKey:
        return AutoGeneratedFileRevisionIDLookupKey(self.auto_generated_file_revision_id)

    @override
    def field_id(self) -> AutoGeneratedFileRevisionID:
        return self.auto_generated_file_revision_id

    @override
    def to_owner_lookup(self) -> AutoGeneratedFileRevisionOwnerLookup:
        return AutoGeneratedFileRevisionOwnerLookup()
