from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass
from typing import Any, override

from ai.backend.common.data.entity.auto_generated_file import (
    AutoGeneratedFileEntityType,
    AutoGeneratedFileID,
)
from ai.backend.common.data.entity.auto_generated_file_revision import AutoGeneratedFileRevisionID
from ai.backend.common.data.entity.types import EntityType
from ai.backend.manager.actions.v2.field.bulk_lookup import LookupBulkFieldOwnerOpsAction
from ai.backend.manager.actions.v2.lookup.base import LookupKey
from ai.backend.manager.models.auto_generated_file_revision.lookups import (
    AutoGeneratedFileRevisionOwnerLookup,
)


@dataclass(frozen=True)
class AutoGeneratedFileRevisionIDLookupKey(LookupKey):
    """A revision's id, resolved into the file it was written to."""

    auto_generated_file_revision_id: AutoGeneratedFileRevisionID

    @override
    def kind(self) -> str:
        return "auto_generated_file_revision_id"

    @override
    def to_dict(self) -> dict[str, Any]:
        return {"auto_generated_file_revision_id": str(self.auto_generated_file_revision_id)}


@dataclass(frozen=True)
class LookupBulkAutoGeneratedFileRevisionOwnerAction(
    LookupBulkFieldOwnerOpsAction[AutoGeneratedFileRevisionID, AutoGeneratedFileID]
):
    """The files several revisions were written to."""

    auto_generated_file_revision_ids: Sequence[AutoGeneratedFileRevisionID]

    @override
    @classmethod
    def entity_type(cls) -> EntityType:
        return AutoGeneratedFileEntityType()

    @override
    @classmethod
    def action_name(cls) -> str:
        return "lookup_bulk_auto_generated_file_revision_owner"

    @override
    def to_lookup_key(self, field_id: AutoGeneratedFileRevisionID) -> LookupKey:
        return AutoGeneratedFileRevisionIDLookupKey(field_id)

    @override
    def field_ids(self) -> Sequence[AutoGeneratedFileRevisionID]:
        return tuple(self.auto_generated_file_revision_ids)

    @override
    def to_owner_lookup(self) -> AutoGeneratedFileRevisionOwnerLookup:
        return AutoGeneratedFileRevisionOwnerLookup()
