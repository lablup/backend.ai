from __future__ import annotations

from dataclasses import dataclass
from typing import override

from ai.backend.common.data.entity.types import EntityIdentifier
from ai.backend.manager.actions.v2.ops.base import UpdateSingleEntityOpsAction
from ai.backend.manager.data.auto_generated_file.types import AutoGeneratedFileData
from ai.backend.manager.models.auto_generated_file.row import AutoGeneratedFileRow
from ai.backend.manager.models.auto_generated_file.updaters import AutoGeneratedFileUpdater


@dataclass(frozen=True)
class UpdateAutoGeneratedFileAction(
    UpdateSingleEntityOpsAction[AutoGeneratedFileRow, AutoGeneratedFileData]
):
    """Rewrite one auto-generated file, named by its own id."""

    updater: AutoGeneratedFileUpdater

    @override
    @classmethod
    def action_name(cls) -> str:
        return "update_auto_generated_file"

    @override
    def entity_id(self) -> EntityIdentifier:
        return self.updater.auto_generated_file_id

    @override
    def to_updater(self) -> AutoGeneratedFileUpdater:
        return self.updater
