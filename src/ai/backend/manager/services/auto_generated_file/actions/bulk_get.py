from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass, replace
from typing import Self, override

from ai.backend.common.data.entity.auto_generated_file import AutoGeneratedFileID
from ai.backend.common.data.entity.types import EntityIdentifier
from ai.backend.manager.actions.v2.ops.base import PartialBulkGetEntityOpsAction
from ai.backend.manager.data.auto_generated_file.types import AutoGeneratedFileData
from ai.backend.manager.models.auto_generated_file.queriers import BulkAutoGeneratedFileQuerier
from ai.backend.manager.models.auto_generated_file.row import AutoGeneratedFileRow


@dataclass(frozen=True)
class BulkGetAutoGeneratedFilesAction(
    PartialBulkGetEntityOpsAction[AutoGeneratedFileRow, AutoGeneratedFileData]
):
    """Read the auto-generated files the caller named, answering for each id."""

    ids: Sequence[AutoGeneratedFileID]

    @override
    @classmethod
    def action_name(cls) -> str:
        return "bulk_get_auto_generated_files"

    @override
    def entity_ids(self) -> Sequence[EntityIdentifier]:
        return tuple(self.ids)

    @override
    def to_querier(self) -> BulkAutoGeneratedFileQuerier:
        return BulkAutoGeneratedFileQuerier()

    @override
    def narrowed_to(self, entity_ids: Sequence[EntityIdentifier]) -> Self:
        allowed = frozenset(entity_ids)
        return replace(self, ids=[entity_id for entity_id in self.ids if entity_id in allowed])
