from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass
from typing import override

from ai.backend.common.data.entity.auto_generated_file import AutoGeneratedFileID
from ai.backend.common.data.entity.types import EntityIdentifier
from ai.backend.manager.actions.v2.ops.base import BulkGetOwnedFieldOpsAction
from ai.backend.manager.data.auto_generated_file.types import AutoGeneratedFileRevisionData
from ai.backend.manager.models.auto_generated_file_revision.queriers import (
    CurrentAutoGeneratedFileRevisionQuerier,
)
from ai.backend.manager.models.auto_generated_file_revision.row import AutoGeneratedFileRevisionRow


@dataclass(frozen=True)
class GetCurrentAutoGeneratedFileRevisionsAction(
    BulkGetOwnedFieldOpsAction[
        AutoGeneratedFileID, AutoGeneratedFileRevisionRow, AutoGeneratedFileRevisionData
    ]
):
    """Read the latest revision of each named file, which is its current content."""

    auto_generated_file_ids: Sequence[AutoGeneratedFileID]

    @override
    def entity_ids(self) -> Sequence[EntityIdentifier]:
        return self.auto_generated_file_ids

    @override
    def owner_ids(self) -> Sequence[AutoGeneratedFileID]:
        return self.auto_generated_file_ids

    @override
    def to_querier(self) -> CurrentAutoGeneratedFileRevisionQuerier:
        return CurrentAutoGeneratedFileRevisionQuerier()

    @override
    @classmethod
    def action_name(cls) -> str:
        return "get_current_auto_generated_file_revisions"
