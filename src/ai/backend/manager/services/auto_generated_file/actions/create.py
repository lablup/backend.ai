from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass
from typing import override

from ai.backend.common.data.entity.auto_generated_file import AutoGeneratedFileEntityType
from ai.backend.common.data.entity.types import EntityIdentifier, EntityType
from ai.backend.manager.actions.types import ActionOperationType
from ai.backend.manager.actions.v2.scope.base import BaseScopeAction
from ai.backend.manager.models.auto_generated_file.creators import AutoGeneratedFileCreator


@dataclass(frozen=True)
class CreateAutoGeneratedFileAction(BaseScopeAction):
    """Add an auto-generated file to the owner the creator names, as the default of its path."""

    creator: AutoGeneratedFileCreator

    @override
    @classmethod
    def entity_type(cls) -> EntityType:
        return AutoGeneratedFileEntityType()

    @override
    @classmethod
    def operation_type(cls) -> ActionOperationType:
        return ActionOperationType.CREATE

    @override
    @classmethod
    def action_name(cls) -> str:
        return "create_auto_generated_file"

    @override
    def scope_targets(self) -> Sequence[EntityIdentifier]:
        return (self.creator.owner,)
