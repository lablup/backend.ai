from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass
from typing import override

from ai.backend.common.data.entity.auto_generated_file import AutoGeneratedFileEntityType
from ai.backend.common.data.entity.types import EntityIdentifier, EntityType
from ai.backend.manager.actions.v2.ops.base import CreateEntityOpsAction
from ai.backend.manager.data.auto_generated_file.types import AutoGeneratedFileData
from ai.backend.manager.models.auto_generated_file.creators import AutoGeneratedFileCreator
from ai.backend.manager.models.auto_generated_file.row import AutoGeneratedFileRow


@dataclass(frozen=True)
class CreateAutoGeneratedFileAction(
    CreateEntityOpsAction[AutoGeneratedFileRow, AutoGeneratedFileData]
):
    """Add an auto-generated file to the owner the creator names."""

    creator: AutoGeneratedFileCreator

    @override
    @classmethod
    def entity_type(cls) -> EntityType:
        return AutoGeneratedFileEntityType()

    @override
    @classmethod
    def action_name(cls) -> str:
        return "create_auto_generated_file"

    @override
    def scope_targets(self) -> Sequence[EntityIdentifier]:
        return (self.creator.owner,)

    @override
    def to_creator(self) -> AutoGeneratedFileCreator:
        return self.creator
