from __future__ import annotations

from dataclasses import dataclass
from typing import override

from ai.backend.common.data.entity.auto_generated_file import AutoGeneratedFileID
from ai.backend.common.data.entity.types import EntityIdentifier
from ai.backend.manager.actions.v2.ops.base import PurgeEntityOpsAction
from ai.backend.manager.data.auto_generated_file.types import AutoGeneratedFileData
from ai.backend.manager.models.auto_generated_file.purgers import AutoGeneratedFilePurger
from ai.backend.manager.models.auto_generated_file.row import AutoGeneratedFileRow


@dataclass(frozen=True)
class PurgeAutoGeneratedFileAction(
    PurgeEntityOpsAction[AutoGeneratedFileRow, AutoGeneratedFileData]
):
    """Remove one auto-generated file with its virtual entity and every edge naming it."""

    auto_generated_file_id: AutoGeneratedFileID

    @override
    @classmethod
    def action_name(cls) -> str:
        return "purge_auto_generated_file"

    @override
    def entity_id(self) -> EntityIdentifier:
        return self.auto_generated_file_id

    @override
    def to_purger(self) -> AutoGeneratedFilePurger:
        return AutoGeneratedFilePurger(auto_generated_file_id=self.auto_generated_file_id)
