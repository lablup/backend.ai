from __future__ import annotations

from dataclasses import dataclass
from typing import override

from ai.backend.common.data.entity.auto_generated_file import AutoGeneratedFileID
from ai.backend.manager.actions.v2.field.lookup import LookupRuntimeFieldOwnerOpsAction
from ai.backend.manager.actions.v2.field.ops import RuntimePurgeFieldOpsAction
from ai.backend.manager.data.auto_generated_file.types import AutoGeneratedFileData
from ai.backend.manager.models.auto_generated_file.purgers import AutoGeneratedFilePurger
from ai.backend.manager.models.auto_generated_file.row import AutoGeneratedFileRow
from ai.backend.manager.services.auto_generated_file.actions.lookup_owner import (
    LookupAutoGeneratedFileOwnerAction,
)


@dataclass
class PurgeAutoGeneratedFileAction(
    RuntimePurgeFieldOpsAction[AutoGeneratedFileID, AutoGeneratedFileRow, AutoGeneratedFileData]
):
    """Remove one file, named by its own id; its owner answers for it."""

    file_id: AutoGeneratedFileID

    @override
    @classmethod
    def action_name(cls) -> str:
        return "purge_auto_generated_file"

    @override
    def to_owner_lookup_action(self) -> LookupRuntimeFieldOwnerOpsAction[AutoGeneratedFileID]:
        return LookupAutoGeneratedFileOwnerAction(file_id=self.file_id)

    @override
    def to_purger(self) -> AutoGeneratedFilePurger:
        return AutoGeneratedFilePurger(file_id=self.file_id)
