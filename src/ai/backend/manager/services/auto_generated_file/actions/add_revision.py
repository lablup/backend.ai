from __future__ import annotations

from dataclasses import dataclass
from typing import override

from ai.backend.common.data.entity.auto_generated_file import AutoGeneratedFileID
from ai.backend.common.data.entity.types import EntityIdentifier
from ai.backend.manager.actions.v2.ops.base import CreateFieldOpsAction
from ai.backend.manager.data.auto_generated_file.types import (
    AutoGeneratedFileRevisionData,
    AutoGeneratedFileRevisionSpec,
)
from ai.backend.manager.models.auto_generated_file_revision.creators import (
    AutoGeneratedFileRevisionCreator,
)
from ai.backend.manager.models.auto_generated_file_revision.row import AutoGeneratedFileRevisionRow


@dataclass(frozen=True)
class AddAutoGeneratedFileRevisionAction(
    CreateFieldOpsAction[
        AutoGeneratedFileID, AutoGeneratedFileRevisionRow, AutoGeneratedFileRevisionData
    ]
):
    """Append the next revision of one file's content."""

    auto_generated_file_id: AutoGeneratedFileID
    revision: AutoGeneratedFileRevisionSpec

    @override
    @classmethod
    def action_name(cls) -> str:
        return "add_auto_generated_file_revision"

    @override
    def entity_id(self) -> EntityIdentifier:
        return self.auto_generated_file_id

    @override
    def owner_id(self) -> AutoGeneratedFileID:
        return self.auto_generated_file_id

    @override
    def to_creator(self) -> AutoGeneratedFileRevisionCreator:
        return AutoGeneratedFileRevisionCreator(revision=self.revision)
