from __future__ import annotations

from dataclasses import dataclass
from typing import override

from ai.backend.common.data.entity.auto_generated_file import AutoGeneratedFileID
from ai.backend.common.data.entity.types import EntityIdentifier
from ai.backend.manager.actions.types import ActionOperationType
from ai.backend.manager.actions.v2.single_entity.base import BaseSingleEntityAction
from ai.backend.manager.data.auto_generated_file.types import AutoGeneratedFileData


@dataclass(frozen=True)
class SwitchDefaultAutoGeneratedFileAction(BaseSingleEntityAction):
    """Make one of the owner's auto-generated files the default of its path."""

    owner: EntityIdentifier
    auto_generated_file_id: AutoGeneratedFileID

    @override
    def entity_id(self) -> EntityIdentifier:
        return self.auto_generated_file_id

    @override
    @classmethod
    def operation_type(cls) -> ActionOperationType:
        return ActionOperationType.UPDATE

    @override
    @classmethod
    def action_name(cls) -> str:
        return "switch_default_auto_generated_file"


@dataclass(frozen=True)
class SwitchDefaultAutoGeneratedFileActionResult:
    data: AutoGeneratedFileData
