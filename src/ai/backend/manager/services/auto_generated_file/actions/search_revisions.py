from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass
from typing import final, override

from ai.backend.common.data.entity.auto_generated_file import (
    AutoGeneratedFileEntityType,
    AutoGeneratedFileID,
)
from ai.backend.common.data.entity.types import EntityIdentifier, EntityType
from ai.backend.manager.actions.v2.ops.base import OperationScopeOpsAction
from ai.backend.manager.data.auto_generated_file.types import AutoGeneratedFileRevisionData
from ai.backend.manager.models.auto_generated_file_revision.row import AutoGeneratedFileRevisionRow
from ai.backend.manager.models.auto_generated_file_revision.scopes import (
    AutoGeneratedFileRevisionTarget,
)
from ai.backend.manager.models.auto_generated_file_revision.searchers import (
    AutoGeneratedFileRevisionSearcher,
)
from ai.backend.manager.models.scopes import OperationScope


@dataclass(frozen=True)
class SearchAutoGeneratedFileRevisionsAction(
    OperationScopeOpsAction[AutoGeneratedFileRevisionRow, AutoGeneratedFileRevisionData]
):
    """Page through the revisions of one file."""

    auto_generated_file_id: AutoGeneratedFileID
    searcher: AutoGeneratedFileRevisionSearcher

    @override
    @classmethod
    def entity_type(cls) -> EntityType:
        return AutoGeneratedFileEntityType()

    @final
    @override
    def scope_targets(self) -> Sequence[EntityIdentifier]:
        return (self.auto_generated_file_id,)

    @final
    @override
    def operation_scopes(self) -> Sequence[OperationScope]:
        return (AutoGeneratedFileRevisionTarget(file_id=self.auto_generated_file_id),)

    @override
    def to_searcher(self) -> AutoGeneratedFileRevisionSearcher:
        return self.searcher

    @override
    @classmethod
    def action_name(cls) -> str:
        return "search_auto_generated_file_revisions"
