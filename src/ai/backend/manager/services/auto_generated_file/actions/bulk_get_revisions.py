from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass, replace
from typing import Self, override

from ai.backend.common.data.entity.auto_generated_file import AutoGeneratedFileID
from ai.backend.common.data.entity.auto_generated_file_revision import AutoGeneratedFileRevisionID
from ai.backend.manager.actions.v2.field.ops import PartialBulkGetFieldOpsAction
from ai.backend.manager.data.auto_generated_file.types import AutoGeneratedFileRevisionData
from ai.backend.manager.models.auto_generated_file_revision.queriers import (
    BulkAutoGeneratedFileRevisionQuerier,
)
from ai.backend.manager.models.auto_generated_file_revision.row import AutoGeneratedFileRevisionRow
from ai.backend.manager.services.auto_generated_file.actions.lookup_bulk_revision_owner import (
    LookupBulkAutoGeneratedFileRevisionOwnerAction,
)


@dataclass(frozen=True)
class BulkGetAutoGeneratedFileRevisionsAction(
    PartialBulkGetFieldOpsAction[
        AutoGeneratedFileRevisionID,
        AutoGeneratedFileID,
        AutoGeneratedFileRevisionRow,
        AutoGeneratedFileRevisionData,
    ]
):
    """Read the revisions the caller named, answering for each one."""

    ids: Sequence[AutoGeneratedFileRevisionID]

    @override
    @classmethod
    def action_name(cls) -> str:
        return "bulk_get_auto_generated_file_revisions"

    @override
    def field_ids(self) -> Sequence[AutoGeneratedFileRevisionID]:
        return tuple(self.ids)

    @override
    def to_owner_lookup_action(self) -> LookupBulkAutoGeneratedFileRevisionOwnerAction:
        return LookupBulkAutoGeneratedFileRevisionOwnerAction(
            auto_generated_file_revision_ids=self.ids
        )

    @override
    def to_querier(self) -> BulkAutoGeneratedFileRevisionQuerier:
        return BulkAutoGeneratedFileRevisionQuerier()

    @override
    def narrowed_to(self, field_ids: Sequence[AutoGeneratedFileRevisionID]) -> Self:
        allowed = frozenset(field_ids)
        return replace(self, ids=[field_id for field_id in self.ids if field_id in allowed])
