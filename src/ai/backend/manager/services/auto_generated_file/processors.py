from __future__ import annotations

from ai.backend.manager.actions.registry.field import LookupFieldGroup
from ai.backend.manager.actions.v2.field.processor import SingleFieldActionProcessor
from ai.backend.manager.actions.v2.ops.result import EntityOpsResult, ScopedFieldsOpsResult
from ai.backend.manager.actions.v2.scope.processor import ScopeActionProcessor
from ai.backend.manager.data.auto_generated_file.types import AutoGeneratedFileData
from ai.backend.manager.services.auto_generated_file.actions.purge import (
    PurgeAutoGeneratedFileAction,
)
from ai.backend.manager.services.auto_generated_file.actions.search import (
    SearchAutoGeneratedFilesAction,
)
from ai.backend.manager.services.auto_generated_file.actions.update import (
    UpdateAutoGeneratedFileAction,
)


class AutoGeneratedFileProcessors:
    """Dotfile operations straight against ops. The owner's kind is a value on the row,
    so the group comes from the registry rather than an entity's own group."""

    search: ScopeActionProcessor[
        SearchAutoGeneratedFilesAction, ScopedFieldsOpsResult[AutoGeneratedFileData]
    ]
    update: SingleFieldActionProcessor[
        UpdateAutoGeneratedFileAction, EntityOpsResult[AutoGeneratedFileData]
    ]
    purge: SingleFieldActionProcessor[
        PurgeAutoGeneratedFileAction, EntityOpsResult[AutoGeneratedFileData]
    ]

    def __init__(self, group: LookupFieldGroup[AutoGeneratedFileData]) -> None:
        self.search = group.search_ops(SearchAutoGeneratedFilesAction)
        self.update = group.runtime_update_ops(UpdateAutoGeneratedFileAction)
        self.purge = group.runtime_purge_ops(PurgeAutoGeneratedFileAction)
