from __future__ import annotations

from ai.backend.manager.actions.registry.group import ProcessorGroup
from ai.backend.manager.actions.v2.ops.result import (
    CreatedEntityOpsResult,
    EntityOpsResult,
    ScopedBatchOpsResult,
)
from ai.backend.manager.actions.v2.scope.processor import ScopeActionProcessor
from ai.backend.manager.actions.v2.single_entity.processor import SingleEntityActionProcessor
from ai.backend.manager.data.auto_generated_file.types import AutoGeneratedFileData
from ai.backend.manager.services.auto_generated_file.actions.create import (
    CreateAutoGeneratedFileAction,
)
from ai.backend.manager.services.auto_generated_file.actions.purge import (
    PurgeAutoGeneratedFileAction,
)
from ai.backend.manager.services.auto_generated_file.actions.search import (
    SearchAutoGeneratedFilesAction,
)
from ai.backend.manager.services.auto_generated_file.actions.switch_default import (
    SwitchDefaultAutoGeneratedFileAction,
    SwitchDefaultAutoGeneratedFileActionResult,
)
from ai.backend.manager.services.auto_generated_file.actions.update import (
    UpdateAutoGeneratedFileAction,
)
from ai.backend.manager.services.user.service import UserService


class AutoGeneratedFileProcessors:
    create: ScopeActionProcessor[
        CreateAutoGeneratedFileAction, CreatedEntityOpsResult[AutoGeneratedFileData]
    ]
    search: ScopeActionProcessor[
        SearchAutoGeneratedFilesAction, ScopedBatchOpsResult[AutoGeneratedFileData]
    ]
    update: SingleEntityActionProcessor[
        UpdateAutoGeneratedFileAction, EntityOpsResult[AutoGeneratedFileData]
    ]
    switch_default: SingleEntityActionProcessor[
        SwitchDefaultAutoGeneratedFileAction, SwitchDefaultAutoGeneratedFileActionResult
    ]
    purge: SingleEntityActionProcessor[
        PurgeAutoGeneratedFileAction, EntityOpsResult[AutoGeneratedFileData]
    ]

    def __init__(
        self, group: ProcessorGroup[AutoGeneratedFileData], user_service: UserService
    ) -> None:
        self.create = group.scope(
            CreateAutoGeneratedFileAction, user_service.create_auto_generated_file
        )
        self.search = group.scope_search_ops(SearchAutoGeneratedFilesAction)
        self.update = group.single_update_ops(UpdateAutoGeneratedFileAction)
        self.switch_default = group.single_entity(
            SwitchDefaultAutoGeneratedFileAction, user_service.switch_default_auto_generated_file
        )
        self.purge = group.entity_purge_ops(PurgeAutoGeneratedFileAction)
